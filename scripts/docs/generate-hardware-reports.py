"""Render docs/hardware-reports/index.md and the table of docs/usage/hardware-we-need.md.

Both come from the report files in docs/hardware-reports/; the table of the page also
reads scripts/docs/hardware-needs.json (the families wanted) and the row maps of
tools/rc1-tester/image/.

Flags:
    --check   Exit 1 when an in-tree output differs from the rendering, when a GPU family
              of a row map has no row in hardware-needs.json, or when a state id is not in
              docs/state.md.
    --write   Rewrite the outputs.

Wired into `make docs-fragments-check` / `make docs-fragments-write` (ADR-0221 pattern).
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "rc1-tester" / "src"))

from vmaf_rc1_tester.hw_report import CHECK_KEYS, PASSING  # noqa: E402

DIRECTORY = ROOT / "docs" / "hardware-reports"
OUTPUT = DIRECTORY / "index.md"
SCHEMA_NAME = "report.schema.json"
NEEDS = ROOT / "scripts" / "docs" / "hardware-needs.json"
NEEDS_PAGE = ROOT / "docs" / "usage" / "hardware-we-need.md"
IMAGE_DIR = ROOT / "tools" / "rc1-tester" / "image"
STATE = ROOT / "docs" / "state.md"
BEGIN = "<!-- hardware-needs:begin (generated by scripts/docs/generate-hardware-reports.py) -->"
END = "<!-- hardware-needs:end -->"
PACKAGES = {
    "macos": ("macOS bundle", "a-native-macos-bundle-apple-silicon"),
    "container": ("container image", "b-container-image"),
    "sycl": ("Intel GPU image", "c-intel-gpu-image-linux-or-windows-with-wsl2"),
    "cuda": ("NVIDIA GPU image", "d-nvidia-gpu-image-linux-or-windows-with-wsl2"),
    "hip": ("AMD GPU image", "e-amd-gpu-image-linux"),
    "windows": ("Windows zip", "f-native-windows-zip-x64-or-arm64"),
    "windows-cuda": ("Windows CUDA zip", "with-an-nvidia-gpu-the-cuda-zip"),
    "windows-sycl": ("Windows SYCL zip", "with-an-intel-gpu-the-sycl-zip"),
}
GPU_BACKENDS = ("cuda", "hip", "sycl")
# The checks of a report that are about the processor (hw_report.CHECK_KEYS names). A CPU
# row takes their verdict, not the report's: a GPU section's failure is a finding about the
# GPU. The native macOS row also closes the Metal rows, so its own checks add Metal's.
CPU_CHECKS = ("dispatch", "reference", "unit", "golden")
METAL_CHECKS = ("metal", "gate")

HEADER = """\
<!-- GENERATED by scripts/docs/generate-hardware-reports.py from the report
files in this directory; do not edit by hand. Add a report file and run
`make docs-fragments-write`. -->

# Hardware reports

Reports printed by the [tester image](../usage/tester-image.md) on machines outside
the project's own hosts, one file per report. The table lists one row per measured
backend: a CPU row for the host's scalar and dispatch checks, a Metal row for
macOS, and one row per CUDA, HIP or SYCL device. Each row links the report file.
The [report schema](report.schema.json) lists every field, and the CI gate
`scripts/ci/check-hardware-reports.py` validates each file. A report with
verdict `fail` is welcome: it is a finding.

The table is filterable in the browser by device text, backend, exactness, result
and operating system. When two reports measure the same backend on the same
device, the newest row is shown and the older report is linked from that row. The
page becomes a view of the result document ([#2311](https://github.com/VMAFx/vmafx/issues/2311))
when that lands.

"""
EMPTY = "No reports have been submitted yet.\n"

TABLE_HEAD = """\
<table class="vx-hardware-table" data-hardware-table>
<thead>
<tr><th>Date</th><th>Device</th><th>Backend</th><th>Driver</th><th>OS</th><th>Host / flags</th><th>Exactness</th><th>Result</th><th>Report</th></tr>
</thead>
<tbody>
"""
TABLE_TAIL = """\
</tbody>
</table>
<p class="vx-hardware-empty" data-hardware-empty hidden>No rows match the filters.</p>
"""

BACKEND_LABELS = {
    "cpu": "CPU",
    "cuda": "CUDA",
    "hip": "HIP",
    "metal": "Metal",
    "sycl": "SYCL",
}


def _platform(report: dict[str, Any]) -> str:
    return str(report["host"].get("platform") or "?")


def _host_cell(report: dict[str, Any], backend: str) -> str:
    host = report["host"]
    if backend == "cpu":
        flags = ", ".join(host.get("dispatch_flags", [])) or "none"
        return f"{host.get('machine', '?')}; {flags}"
    return str(host.get("cpu_model") or "?")


def _driver(report: dict[str, Any], backend: str, facts: dict[str, Any]) -> str:
    if backend == "cpu":
        return str(report["host"].get("kernel_release") or "not reported")
    if backend == "metal":
        return "not reported"
    values = [str(facts[key]) for key in ("driver_version", "code_path") if facts.get(key)]
    return " / ".join(values) or "not reported"


def _cpu_exactness(report: dict[str, Any]) -> str:
    statuses = [
        str(section.get("status"))
        for key in ("dispatch_equivalence", "reference_equivalence")
        if (section := report.get(key)) and section.get("status")
    ]
    if not statuses:
        return "not_measured"
    if all(status == "identical" for status in statuses):
        return "identical"
    return next(status for status in statuses if status != "identical")


def _gpu_key(backend: str, facts: dict[str, Any]) -> str:
    vendor = str(facts.get("vendor_id") or "")
    device_id = str(facts.get("device_id") or "")
    if vendor and device_id:
        return f"{backend}:{vendor}:{device_id}"
    name = str(facts.get("name") or "?").casefold()
    return f"{backend}:{name}:{facts.get('compute_capability', '')}:{facts.get('family', '')}"


def _backend_label(backend: str) -> str:
    return BACKEND_LABELS.get(backend, backend.upper())


def _rows_for_report(path: Path, report: dict[str, Any]) -> list[dict[str, Any]]:
    """One row per measured backend: CPU, Metal and every GPU device."""
    host = report["host"]
    date = report["generated_utc"][:10]
    stamp = report["generated_utc"]
    platform = _platform(report)
    cpu_exactness = _cpu_exactness(report)
    rows = [
        {
            "key": f"cpu:{platform}:{host.get('machine', '?')}:{host.get('cpu_model', '?')}",
            "date": date,
            "stamp": stamp,
            "report": path.name,
            "device": str(host.get("cpu_model") or "?"),
            "backend": "cpu",
            "driver": _driver(report, "cpu", {}),
            "platform": platform,
            "host": _host_cell(report, "cpu"),
            "exactness": f"cpu {cpu_exactness}",
            "exactness_status": cpu_exactness,
            "result": _host_verdict({}, report),
        }
    ]

    metal = report.get("metal_equivalence") or {}
    metal_status = metal.get("status")
    if metal_status and metal_status not in ("not_applicable", "no_device"):
        rows.append(
            {
                "key": f"metal:{host.get('cpu_model', '?')}:{host.get('machine', '?')}",
                "date": date,
                "stamp": stamp,
                "report": path.name,
                "device": f"{host.get('cpu_model', '?')} (Metal)",
                "backend": "metal",
                "driver": _driver(report, "metal", {}),
                "platform": platform,
                "host": str(host.get("cpu_model") or "?"),
                "exactness": f"metal {metal_status}",
                "exactness_status": str(metal_status),
                "result": str(metal_status),
            }
        )

    gpu = report.get("gpu") or {}
    backend = gpu.get("backend")
    if backend:
        for device in gpu.get("devices", []):
            facts = device.get("facts", {})
            status = str(device.get("status") or "not_measured")
            name = str(facts.get("name") or "?")
            rows.append(
                {
                    "key": _gpu_key(str(backend), facts),
                    "date": date,
                    "stamp": stamp,
                    "report": path.name,
                    "device": name,
                    "backend": str(backend),
                    "driver": _driver(report, str(backend), facts),
                    "platform": platform,
                    "host": str(host.get("cpu_model") or "?"),
                    "exactness": f"{backend} {status}",
                    "exactness_status": status,
                    "result": status,
                }
            )
    return rows


def _collect_rows(directory: Path) -> list[dict[str, Any]]:
    """The rows of every report, with the newest row kept per device key."""
    rows: list[dict[str, Any]] = []
    for path in (p for p in sorted(directory.glob("*.json")) if p.name != SCHEMA_NAME):
        rows.extend(_rows_for_report(path, json.loads(path.read_text(encoding="utf-8"))))

    kept: dict[str, dict[str, Any]] = {}
    for row in rows:
        current = kept.get(row["key"])
        if current is None:
            kept[row["key"]] = row
            continue
        row["older"] = [*list(current.get("older", [])), (current["date"], current["report"])]
        if (row["stamp"], row["report"]) > (current["stamp"], current["report"]):
            kept[row["key"]] = row
        else:
            current.setdefault("older", []).append((row["date"], row["report"]))
    for row in kept.values():
        older = sorted(
            {item for item in row.get("older", []) if item[1] != row["report"]},
            reverse=True,
        )
        row["older"] = older
    return sorted(
        kept.values(),
        key=lambda row: (row["stamp"], row["backend"], row["device"]),
        reverse=True,
    )


def _options(values: list[str], label: Any = str) -> str:
    return "".join(
        f'<option value="{html.escape(value, quote=True)}">{html.escape(label(value))}</option>'
        for value in values
    )


def _filter(rows: list[dict[str, Any]]) -> str:
    backends = sorted({row["backend"] for row in rows}, key=_backend_label)
    statuses = sorted({row["exactness_status"] for row in rows})
    results = sorted({row["result"] for row in rows})
    platforms = sorted({row["platform"] for row in rows})
    return (
        '<div class="vx-hardware-filter" data-hardware-filter>'
        '<label>Search <input type="search" data-hardware-search '
        'placeholder="device, driver, host, report"></label>'
        f'<label>Backend <select data-hardware-backend><option value="">all</option>'
        f"{_options(backends, _backend_label)}</select></label>"
        f'<label>Exactness <select data-hardware-exactness><option value="">all</option>'
        f"{_options(statuses)}</select></label>"
        f'<label>Result <select data-hardware-result><option value="">all</option>'
        f"{_options(results)}</select></label>"
        f'<label>OS <select data-hardware-platform><option value="">all</option>'
        f"{_options(platforms)}</select></label>"
        '<span data-hardware-count aria-live="polite"></span>'
        "</div>"
    )


def _device_cell(row: dict[str, Any]) -> str:
    text = html.escape(row["device"])
    older = row.get("older") or []
    if not older:
        return text
    links = ", ".join(
        f'<a href="{html.escape(name, quote=True)}">{html.escape(date)}</a>' for date, name in older
    )
    return f'{text}<br><span class="vx-hardware-older">older: {links}</span>'


def _row_html(row: dict[str, Any]) -> str:
    search = " ".join(
        [
            row["date"],
            row["device"],
            row["backend"],
            row["driver"],
            row["platform"],
            row["host"],
            row["exactness"],
            row["result"],
            row["report"],
        ]
        + [date for date, _ in row.get("older", [])]
    ).casefold()
    attributes = (
        f'data-backend="{html.escape(row["backend"], quote=True)}" '
        f'data-exactness="{html.escape(row["exactness_status"], quote=True)}" '
        f'data-result="{html.escape(row["result"], quote=True)}" '
        f'data-platform="{html.escape(row["platform"], quote=True)}" '
        f'data-search="{html.escape(search, quote=True)}"'
    )
    return (
        f"<tr data-hardware-row {attributes}>"
        f"<td>{html.escape(row['date'])}</td>"
        f"<td>{_device_cell(row)}</td>"
        f"<td>{html.escape(_backend_label(row['backend']))}</td>"
        f"<td>{html.escape(row['driver'])}</td>"
        f"<td>{html.escape(row['platform'])}</td>"
        f"<td>{html.escape(row['host'])}</td>"
        f"<td>{html.escape(row['exactness'])}</td>"
        f"<td>{html.escape(row['result'])}</td>"
        f'<td><a href="{html.escape(row["report"], quote=True)}">'
        f"{html.escape(row['report'])}</a></td>"
        "</tr>"
    )


def render(directory: Path) -> str:
    paths = [p for p in sorted(directory.glob("*.json")) if p.name != SCHEMA_NAME]
    if not paths:
        return HEADER + EMPTY
    rows = _collect_rows(directory)
    return (
        HEADER
        + _filter(rows)
        + "\n"
        + TABLE_HEAD
        + "\n".join(_row_html(row) for row in rows)
        + "\n"
        + TABLE_TAIL
    )


def _host_matches(match: dict[str, Any], report: dict[str, Any]) -> bool:
    """Whether a report's host satisfies the CPU part of a row's `match`."""
    host = report["host"]
    flags = set(host["dispatch_flags"])
    return (
        ("platform" not in match or host["platform"] == match["platform"])
        and ("machine" not in match or host["machine"] in match["machine"])
        and set(match.get("flags_all", [])) <= flags
        and not set(match.get("flags_none", [])) & flags
        and (
            "cpu_model_re" not in match or bool(re.search(match["cpu_model_re"], host["cpu_model"]))
        )
    )


def _gpu_verdicts(match: dict[str, Any], report: dict[str, Any]) -> list[str]:
    """One verdict per device of the report that belongs to the row's GPU families (and,
    when the row names one, ran on its platform)."""
    gpu = report.get("gpu") or {}
    if gpu.get("backend") != match["gpu_backend"]:
        return []
    if "platform" in match and report["host"]["platform"] != match["platform"]:
        return []
    found = []
    for device in gpu.get("devices", []):
        if device["facts"].get("family") in match["gpu_families"]:
            rows = device["rows"]["status"]
            found.append("fail" if "fail" in (device["status"], rows) else rows)
    return found


def _host_verdict(row: dict[str, Any], report: dict[str, Any]) -> str:
    """`fail` when one of the row's own checks failed (or the image's files do not match
    its build), else `pass`. A section an older schema lacks is not counted."""
    checks = CPU_CHECKS + (METAL_CHECKS if row.get("metal_rows") else ())
    keys = [CHECK_KEYS[check] for check in checks]
    failed = [k for k in keys if k in report and report[k]["status"] not in PASSING[k]]
    if failed or not report["image"]["files_match_build"]:
        return "fail"
    return "pass"


def _verdicts(row: dict[str, Any], reports: list[dict[str, Any]]) -> list[str]:
    """The verdict of every report (every device, for a GPU row) that counts for a row."""
    match = row["match"]
    found: list[str] = []
    for report in reports:
        if "gpu_backend" in match:
            found += _gpu_verdicts(match, report)
        elif _host_matches(match, report):
            found.append(_host_verdict(row, report))
    return found


def _status(row: dict[str, Any], reports: list[dict[str, Any]]) -> str:
    verdicts = _verdicts(row, reports)
    owner = f"covered by {row['owner']}" if row["owner"] else ""
    if not verdicts:
        return owner or "no report yet"
    worst = (
        "fail" if "fail" in verdicts else ("pass" if "pass" in verdicts else "not fully measured")
    )
    reported = f"{len(verdicts)} reported, worst {worst}"
    return f"{owner}; {reported}" if owner else reported


def _state_cell(row: dict[str, Any], metal_count: int) -> str:
    cells = [f"[`{i}`](../state.md)" for i in row["state"]]
    if row.get("metal_rows"):
        cells.append(
            f"the {metal_count} open Metal rows ([list](tester-image.md#metal-state-rows))"
        )
    return ", ".join(cells)


def render_needs_table(needs: dict[str, Any], reports: list[dict[str, Any]]) -> str:
    metal = json.loads((IMAGE_DIR / "metal-rows.json").read_text(encoding="utf-8"))
    head = (
        "| Hardware family | Run this package | Closes (state row) | Status |\n"
        "| --- | --- | --- | --- |\n"
    )
    lines = []
    for row in needs["rows"]:
        name, anchor = PACKAGES[row["package"]]
        cells = [
            row["family"],
            f"[{name}](tester-image.md#{anchor})",
            _state_cell(row, len(metal["rows"])),
            _status(row, reports),
        ]
        lines.append("| " + " | ".join(c.replace("|", "/") for c in cells) + " |")
    return head + "\n".join(lines) + "\n"


def needs_problems(needs: dict[str, Any]) -> list[str]:
    """Rows that disagree with the row maps or the state ledger."""
    problems = []
    for backend in GPU_BACKENDS:
        wanted = json.loads((IMAGE_DIR / f"{backend}-rows.json").read_text(encoding="utf-8"))
        mapped = {f for row in wanted["rows"] for f in row.get("families", [])}
        # A row bound to one platform (a Windows GPU zip's) covers no family: every
        # family still needs its own row.
        listed = {
            f
            for row in needs["rows"]
            if row["match"].get("gpu_backend") == backend and "platform" not in row["match"]
            for f in row["match"]["gpu_families"]
        }
        problems += [
            f"{backend} family {f} has no row in {NEEDS.name}" for f in sorted(mapped - listed)
        ]
        problems += [
            f"{backend} family {f} of {NEEDS.name} is in no row map"
            for f in sorted(listed - mapped)
        ]
    state = STATE.read_text(encoding="utf-8")
    ids = {i for row in needs["rows"] for i in row["state"]}
    problems += [
        f"state id {i} is not in docs/state.md" for i in sorted(ids) if f"**{i}**" not in state
    ]
    problems += [
        f"unknown package {r['package']}" for r in needs["rows"] if r["package"] not in PACKAGES
    ]
    return problems


def splice(page: str, table: str) -> str:
    """The page with the text between the two markers replaced by the table."""
    head, sep, rest = page.partition(BEGIN)
    if not sep or END not in rest:
        raise ValueError(f"{NEEDS_PAGE.name} lacks the {BEGIN!r} / {END!r} markers")
    tail = rest.partition(END)[2]
    return f"{head}{BEGIN}\n\n{table}\n{END}{tail}"


def load_reports(directory: Path) -> list[dict[str, Any]]:
    paths = [p for p in sorted(directory.glob("*.json")) if p.name != SCHEMA_NAME]
    return [json.loads(p.read_text(encoding="utf-8")) for p in paths]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    needs = json.loads(NEEDS.read_text(encoding="utf-8"))
    problems = needs_problems(needs)
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        return 1
    outputs = {
        OUTPUT: render(DIRECTORY),
        NEEDS_PAGE: splice(
            NEEDS_PAGE.read_text(encoding="utf-8"),
            render_needs_table(needs, load_reports(DIRECTORY)),
        ),
    }
    stale = [
        p for p, text in outputs.items() if not p.is_file() or p.read_text(encoding="utf-8") != text
    ]
    if args.write:
        for path in stale:
            path.write_text(outputs[path], encoding="utf-8")
        return 0
    for path in stale:
        print(
            f"{path.relative_to(ROOT)} is stale; run `make docs-fragments-write`", file=sys.stderr
        )
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
