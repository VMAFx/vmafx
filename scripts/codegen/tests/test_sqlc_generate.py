"""scripts/codegen/sqlc_generate.py (ADR-2350 D1): the drift gate of the
sqlc-generated store queries.

A stand-in sqlc (a Python script that reports the pinned version and writes a
fixed file) drives the real write and check paths, so the gate is shown
refusing a hand edit, a stale file and a missing file, and skipping (77) with
its reason when no pinned binary exists for the host. The stand-in runs on
every host: a script with this interpreter in its #! line on POSIX, a .cmd
that calls this interpreter on Windows, which cannot start a #! script
("%1 is not a valid Win32 application", WinError 193).
"""

from __future__ import annotations

import importlib.util
import io
import os
import stat
import sys
import tempfile
import textwrap
import unittest
from contextlib import redirect_stdout
from pathlib import Path
from unittest import mock

SCRIPT = Path(__file__).resolve().parents[1] / "sqlc_generate.py"
SPEC = importlib.util.spec_from_file_location("sqlc_generate", SCRIPT)
assert SPEC is not None and SPEC.loader is not None
sg = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(sg)

CONFIG = "svc/store/sqlc.yaml"
FAKE_SQLC = textwrap.dedent("""\
    import pathlib
    import sys

    if sys.argv[1:2] == ["version"]:
        print("v9.9.9")
        sys.exit(0)
    out = pathlib.Path(sys.argv[3]).parent / "pgdb"
    out.mkdir(parents=True, exist_ok=True)
    (out / "db.go").write_bytes(b"// Code generated by sqlc. DO NOT EDIT.\\n\\npackage pgdb\\n")
    """)


def stand_in(directory: Path) -> Path:
    """The fake sqlc as a program this host can start."""
    script = directory / "sqlc.py"
    script.write_text(FAKE_SQLC, encoding="utf-8")
    if os.name == "nt":
        launcher = directory / "sqlc.cmd"
        launcher.write_text(f'@"{sys.executable}" "{script}" %*\r\n', encoding="utf-8")
        return launcher
    launcher = directory / "sqlc"
    launcher.write_text(f"#!{sys.executable}\n{FAKE_SQLC}", encoding="utf-8")
    launcher.chmod(launcher.stat().st_mode | stat.S_IXUSR)
    return launcher


class Fixture:
    """A scratch repository with one sqlc configuration and a fake sqlc."""

    def __init__(self, tmp: Path) -> None:
        self.root = tmp / "repo"
        (self.root / "svc" / "store").mkdir(parents=True)
        (self.root / CONFIG).write_text("version: '2'\n", encoding="utf-8")
        (self.root / "build-config.env").write_text('SQLC_VERSION="9.9.9"\n', encoding="utf-8")
        self.sqlc = stand_in(tmp)
        self.generated = self.root / "svc" / "store" / "pgdb" / "db.go"

    def run(self, mode: str, env: dict[str, str] | None = None) -> tuple[int, str]:
        out = io.StringIO()
        environ = {"VMAFX_SQLC": str(self.sqlc)} if env is None else env
        with (
            mock.patch.dict(os.environ, environ, clear=False),
            mock.patch.object(sg, "CONFIGS", {CONFIG: ("pgdb",)}),
            redirect_stdout(out),
        ):
            code = sg.run(self.root, mode)
        return code, out.getvalue()


class SqlcGenerateTest(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.fx = Fixture(Path(self._tmp.name))

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def test_write_adds_the_header_and_check_passes(self) -> None:
        self.assertEqual(self.fx.run("write")[0], 0)
        self.assertTrue(self.fx.generated.read_text(encoding="utf-8").startswith(sg.HEADER))
        self.assertEqual(self.fx.run("check")[0], 0)

    def test_check_refuses_a_hand_edit(self) -> None:
        self.fx.run("write")
        with self.fx.generated.open("a", encoding="utf-8") as fh:
            fh.write("// hand edit\n")
        code, out = self.fx.run("check")
        self.assertEqual(code, 1)
        self.assertIn("differs: svc/store/pgdb/db.go", out)

    def test_check_refuses_stale_and_missing_files(self) -> None:
        self.fx.run("write")
        stale = self.fx.generated.with_name("old.go")
        stale.write_text("package pgdb\n", encoding="utf-8")
        code, out = self.fx.run("check")
        self.assertEqual(code, 1)
        self.assertIn("stale: svc/store/pgdb/old.go", out)
        stale.unlink()
        self.fx.generated.unlink()
        code, out = self.fx.run("check")
        self.assertEqual(code, 1)
        self.assertIn("missing: svc/store/pgdb/db.go", out)

    def test_write_removes_stale_files(self) -> None:
        self.fx.run("write")
        stale = self.fx.generated.with_name("old.go")
        stale.write_text("package pgdb\n", encoding="utf-8")
        self.fx.run("write")
        self.assertFalse(stale.exists())

    def test_check_skips_with_a_reason_without_a_pinned_binary(self) -> None:
        cache = Path(self._tmp.name) / "cache"
        with mock.patch.object(
            sg, "platform_key", side_effect=sg.Unavailable("no pinned sqlc release for test")
        ):
            code, out = self.fx.run("check", env={"XDG_CACHE_HOME": str(cache), "VMAFX_SQLC": ""})
        self.assertEqual(code, sg.SKIP)
        self.assertIn("SKIP: no pinned sqlc release", out)

    def test_a_binary_of_another_version_is_refused(self) -> None:
        (self.fx.root / "build-config.env").write_text('SQLC_VERSION="1.0.0"\n', encoding="utf-8")
        with self.assertRaises(SystemExit) as ctx:
            self.fx.run("check")
        self.assertIn("need v1.0.0", str(ctx.exception))

    def test_header_is_added_once(self) -> None:
        once = sg.with_header("package x\n")
        self.assertEqual(sg.with_header(once), once)

    def test_build_config_reads_quoted_values_only(self) -> None:
        path = Path(self._tmp.name) / "env"
        path.write_text('A="1"\n# B="2"\nC=3\nD_E="x y"\n', encoding="utf-8")
        self.assertEqual(sg.build_config(path), {"A": "1", "D_E": "x y"})


if __name__ == "__main__":
    unittest.main()
