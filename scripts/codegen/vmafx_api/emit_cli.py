"""The `vmaf` command line's option table and usage text (design section 3.5).

`core/tools/cli_options.gen.inc` holds the `getopt_long()` short option string,
the identifiers of the long-only options, the `long_opts[]` table and the
usage lines. `core/tools/cli_parse.cpp` includes it inside its anonymous
namespace and keeps only the value parsers, so a flag, an alias or a help line
can only be added in the definition.
"""

from __future__ import annotations

import textwrap

from .ctext import licence_block
from .model import Api, Option
from .options import all_options

USAGE_WIDTH = 80  # columns of a printed usage line
USAGE_INDENT = 31  # column where the description starts
FIRST_ID = 256  # long-only identifiers start above every short option letter
BANNER = (
    "/* GENERATED by scripts/codegen/vmafx-api.py from core/api/vmafx.toml (ADR-1852),\n"
    " * option groups. Do not edit: change the definition and run\n"
    " * `python3 scripts/codegen/vmafx-api.py --write`. Included by\n"
    " * core/tools/cli_parse.cpp inside its anonymous namespace. */\n"
)


def cli_options(api: Api) -> list[Option]:
    """Every option the command line spells, in definition order."""
    return [o for _, o in all_options(api.option_groups) if o.cli is not None]


def _takes_value(option: Option) -> bool:
    return option.type != "bool" and not (option.cli and option.cli.values)


def short_string(api: Api) -> str:
    """The `getopt_long()` short option string ("r:d:...nvq")."""
    out = ""
    for option in cli_options(api):
        assert option.cli is not None
        if option.cli.short:
            out += option.cli.short + (":" if _takes_value(option) else "")
    return out


def identifiers(api: Api) -> list[str]:
    """Long-only option identifiers, in definition order."""
    out: list[str] = []
    for option in cli_options(api):
        assert option.cli is not None
        if option.cli.values:
            out += [f"{option.cli.ident}_{value.upper()}" for value, _ in option.cli.values]
        elif not option.cli.ident.startswith("'"):
            out.append(option.cli.ident)
    return out


def long_entries(api: Api) -> list[tuple[str, int, str]]:
    """(name without dashes, has_arg, getopt value) for every long spelling."""
    out: list[tuple[str, int, str]] = []
    for option in cli_options(api):
        assert option.cli is not None
        has_arg = 1 if _takes_value(option) else 0
        out += [(flag[2:], has_arg, option.cli.ident) for flag in option.cli.flags]
        out += [(flag[2:], 0, f"{option.cli.ident}_{v.upper()}") for v, flag in option.cli.values]
    return out


def _values_text(option: Option) -> str:
    if option.values:
        return " One of: " + "|".join(option.values) + "."
    if option.choices:
        return " One of: " + "|".join(str(c) for c in option.choices) + "."
    return ""


def _default_text(option: Option) -> str:
    value = option.default_on("cli")
    if option.default_macro:
        return f" (default: {option.default_macro})"
    if value is None or isinstance(value, bool) or value == "":
        return ""
    return f" (default: {value})"


def _wrap(head: str, text: str) -> list[str]:
    width = USAGE_WIDTH - USAGE_INDENT
    body = textwrap.wrap(text, width=width, break_on_hyphens=False, break_long_words=False) or [""]
    pad = " " * USAGE_INDENT
    if len(head) < USAGE_INDENT:
        first = [head.ljust(USAGE_INDENT) + body[0]]
        rest = body[1:]
    else:
        first = [head]
        rest = body
    return [*first, *(pad + line for line in rest)]


def _head(option: Option) -> str:
    assert option.cli is not None
    names = ", ".join(option.cli.flags)
    short = f"/-{option.cli.short}" if option.cli.short else ""
    meta = f" {option.cli.meta}" if option.cli.meta else ""
    return f" {names}{short}{meta}:"


def usage_lines(api: Api) -> list[str]:
    """The usage text after the `Usage:` line, one entry per printed line."""
    lines = ["Supported options:"]
    for option in cli_options(api):
        assert option.cli is not None
        if option.cli.values:
            for value, flag in option.cli.values:
                mark = " (default)" if value == option.default_on("cli") else ""
                lines += _wrap(f" {flag}:", f"{option.doc} {value}{mark}")
            continue
        lines += _wrap(_head(option), option.doc + _values_text(option) + _default_text(option))
    return lines


def _c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _enum_block(api: Api) -> list[str]:
    ids = identifiers(api)
    out = ["enum : std::uint16_t {"]
    out += [f"    {name}{' = ' + str(FIRST_ID) if i == 0 else ''}," for i, name in enumerate(ids)]
    return [*out, "};"]


def _table_block(api: Api) -> list[str]:
    out = ["const struct option long_opts[] = {"]
    for name, has_arg, ident in long_entries(api):
        out.append(
            f'    {{.name = "{name}", .has_arg = {has_arg}, .flag = nullptr, .val = {ident}}},'
        )
    out.append("    {.name = nullptr, .has_arg = 0, .flag = nullptr, .val = 0},")
    return [*out, "};"]


def _usage_block(api: Api) -> list[str]:
    out = ["const char *const usage_lines[] = {"]
    out += [f"    {_c_string(line)}," for line in usage_lines(api)]
    return [*out, "};"]


def include_text(api: Api) -> str:
    """core/tools/cli_options.gen.inc."""
    parts = [
        licence_block() + "\n" + BANNER,
        "// clang-format off",
        f"const char short_opts[] = {_c_string(short_string(api))};",
        "",
        *_enum_block(api),
        "",
        *_table_block(api),
        "",
        *_usage_block(api),
        "// clang-format on",
    ]
    return "\n".join(parts) + "\n"
