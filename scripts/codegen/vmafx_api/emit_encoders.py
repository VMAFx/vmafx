"""Surfaces generated from the encoder registry (ADR-3388).

- `pkg/encoderregistry/registry.gen.json`: embedded by the Go
  `pkg/encoderregistry` package (read by `pkg/encoder` and `pkg/codecadapter`);
- `tools/vmaf-tune/src/vmaftune/codec_adapters/registry.gen.json`: read by the
  Python vmaf-tune adapters, byte-identical to the Go copy;
- `docs/usage/encoder-registry.md`: the table for readers.

Both packages read the adapter facts (quality knob, windows, presets) from the
same document, so neither spells a quality window or a codec list by hand.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from typing import Any

from .encoders import Encoder, Registry, Variant

OUTPUTS = (
    "pkg/encoderregistry/registry.gen.json",
    "tools/vmaf-tune/src/vmaftune/codec_adapters/registry.gen.json",
)
DOCS = "docs/usage/encoder-registry.md"
COMMENT = (
    "GENERATED by scripts/codegen/vmafx-api.py from api/vmafx-encoders.toml (ADR-3388). "
    "Do not edit: change the definition and run `python3 scripts/codegen/vmafx-api.py --write`."
)


def _encoder(row: Encoder) -> dict[str, Any]:
    out = asdict(row)
    out["class"] = out.pop("klass")
    return out


def document(registry: Registry) -> dict[str, Any]:
    return {
        "$comment": COMMENT,
        "encoders": [_encoder(e) for e in registry.encoders],
        "variants": [asdict(v) for v in registry.variants],
    }


def registry_json(registry: Registry) -> str:
    return json.dumps(document(registry), indent=2) + "\n"


def _cell(text: str) -> str:
    return text.replace("|", "\\|") if text else "—"


def _encoder_line(row: Encoder) -> str:
    cells = (
        f"`{row.id}`",
        row.family,
        row.klass,
        row.paradigm,
        row.status,
        f"`{row.ffmpeg_encoder}`" if row.ffmpeg_encoder else row.interface,
        row.hardware,
        row.licence_class,
        row.maintenance,
        ", ".join(row.use_cases + row.artifact_domains),
        ", ".join(row.surfaces),
        row.checked,
    )
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def _variant_line(row: Variant) -> str:
    cells = (f"`{row.adapter}@{row.variant}`", row.kind, row.status, row.licence_class, row.checked)
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


HEAD = """<!-- markdownlint-disable MD013 -->
<!-- {comment} -->

# Encoder registry

VMAFx keeps one list of every video encoder it knows about in
[`api/vmafx-encoders.toml`](https://github.com/VMAFx/vmafx/blob/master/api/vmafx-encoders.toml)
([ADR-3388](../adr/3388-central-encoder-registry.md)). The Go `vmafx-tune`
(`pkg/encoder`) and the Python `vmaf-tune` read their quality knobs, quality
windows and presets from it, so the two tools cannot disagree about a codec.

A row whose status is `implemented` runs today on the surfaces it names. Every
other row is a gap that is planned, only listed (proprietary or reference
software), or waiting for a licence decision. `checked` is the date the row's
upstream state and licence were last verified;
`python3 scripts/codegen/check-encoder-upstreams.py` repeats that check against
FFmpeg master and each row's forge. Rows of class `distortion-source` are not
delivery candidates: they produce one degradation corpus per artifact domain
(DCT blocking, wavelet blur, vector-quantisation mosaic, lossless reference) to
calibrate the metrics.

To use an encoder, pass its id to the subcommand's `--encoder` or `--codec`
option (for example `vmaf-tune corpus --encoder libx265` or
`vmafx-tune ladder --codec libsvtav1`; the option name depends on the
subcommand, not on the tool); pass `ID@VARIANT` to select a fork build
([ADR-0644](../adr/0644-vmaf-tune-codec-runtime-variants.md)).

## Encoders

| Id | Family | Class | Paradigm | Status | FFmpeg encoder | Hardware | Licence class | Upstream | Use cases | Surfaces | Checked |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
"""

VARIANTS_HEAD = """
## Variants

| Token | Kind | Status | Licence class | Checked |
| --- | --- | --- | --- | --- |
"""


def docs_page(registry: Registry) -> str:
    lines = [HEAD.format(comment=COMMENT)]
    lines.extend(_encoder_line(e) + "\n" for e in registry.encoders)
    lines.append(VARIANTS_HEAD)
    lines.extend(_variant_line(v) + "\n" for v in registry.variants)
    return "".join(lines)


def files(registry: Registry) -> dict[str, str]:
    text = registry_json(registry)
    out = dict.fromkeys(OUTPUTS, text)
    out[DOCS] = docs_page(registry)
    return out
