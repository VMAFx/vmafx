def _safe_constants(api: Api) -> str:
    major, minor, patch = api.abi_version
    out = [
        "\n/// Major ABI version of the `VMAFx` definition this binding was generated from.\n",
        f"pub const ABI_VERSION_MAJOR: u32 = {major};\n",
        "/// Minor ABI version of the `VMAFx` definition this binding was generated from.\n",
        f"pub const ABI_VERSION_MINOR: u32 = {minor};\n",
        "/// Patch ABI version of the `VMAFx` definition this binding was generated from.\n",
        f"pub const ABI_VERSION_PATCH: u32 = {patch};\n",
        "/// ABI version `(major, minor, patch)` of the `VMAFx` definition.\n",
        f"pub const ABI_VERSION: (u32, u32, u32) = ({major}, {minor}, {patch});\n",
    ]
    for item in api.enums:
        prefix = "VMAFX_" + "_".join(item.values[0].name.split("_")[1:-1]) + "_"
        cls = short(item.name)
        out.append(f"\n{_doc_lines(item.doc)}pub struct {cls};\n\nimpl {cls} {{\n")
        for val in item.values:
            vdoc = val.doc or f"`{val.name}`."
            out.append(_doc_lines(vdoc, "    "))
            out.append(f"    pub const {val.name.removeprefix(prefix)}: u32 = {val.value};\n")
        out.append("}\n")
        for val in item.values:
            vdoc = val.doc or f"`{val.name}`."
            out.append(
                f"\n{_doc_lines(vdoc)}pub const {val.name.removeprefix('VMAFX_')}: u32 = {val.value};\n"
            )
    for flags in api.flags:
        prefix = upper_snake(flags.name).removesuffix("FLAGS")
        cls = short(flags.name)
        rtype = SAFE_TYPES[flags.type]
        out.append(f"\n{_doc_lines(flags.doc)}pub struct {cls};\n\nimpl {cls} {{\n")
        for bit in flags.bits:
            bdoc = bit.doc or f"`{bit.name}`."
            out.append(_doc_lines(bdoc, "    "))
            out.append(
                f"    pub const {bit.name.removeprefix(prefix)}: {rtype} = 1 << {bit.bit};\n"
            )
        out.append("}\n")
        for bit in flags.bits:
            bdoc = bit.doc or f"`{bit.name}`."
            out.append(
                f"\n{_doc_lines(bdoc)}pub const {bit.name.removeprefix('VMAFX_')}: {rtype} = 1 << {bit.bit};\n"
            )
    return "".join(out)


def _safe_record_field(api: Api, fld: Field) -> tuple[str, str] | None:
    kind = typesys.kind(api, fld.type)
    raw = f"raw.{fld.name}"
    if kind == "struct":
        rec = short(fld.type)
        if fld.count:
            return f"[{rec}; {fld.count}]", f"{raw}.map({rec}::from_c)"
        return rec, f"{rec}::from_c({raw})"
    if kind != "scalar" or fld.type in POINTERS:
        return None
    rtype = SAFE_TYPES[fld.type]
    if fld.count:
        return f"[{rtype}; {fld.count}]", raw
    conv = {
        "cstr": f"c_str_ptr_to_string({raw})",
        "status": f"Status::from_raw({raw}).unwrap_or(Status::EInternal)",
    }
    return rtype, conv.get(fld.type, raw)


def _safe_record_struct(api: Api, item: Struct) -> str:
    fields = [f for f in item.fields if f.name != "struct_size"]
    kept = [(f, v) for f in fields if (v := _safe_record_field(api, f)) is not None]
    rec = short(item.name)
    has_status = any(f.type == "status" for f, _ in kept)
    derives = "Clone, Debug, PartialEq" if has_status else "Clone, Debug, Default, PartialEq"
    out = [f"\n{_doc_lines(item.doc)}#[derive({derives})]\npub struct {rec} {{\n"]
    for fld, (rtype, _) in kept:
        out.append(_doc_lines(fld.doc, "    "))
        out.append(f"    pub {fld.name}: {rtype},\n")
    out.append(f"}}\n\nimpl {rec} {{\n")
    out.append(f"    /// Convert a raw `{item.name}` from the C API.\n    #[must_use]\n")
    out.append(f"    pub fn from_c(raw: sys::{item.name}) -> Self {{\n")
    if len(kept) == 1 and len(f"{kept[0][0].name}: {kept[0][1][1]}") <= SHORT_LIT_WIDTH:
        out.append(f"        Self {{ {kept[0][0].name}: {kept[0][1][1]} }}\n    }}\n")
    else:
        out.append("        Self {\n")
        for fld, (_, expr) in kept:
            out.append(f"            {fld.name}: {expr},\n")
        out.append("        }\n    }\n")
    plain = [f for f, _ in kept]
    if _plain(api, plain):
        out.append(f"\n    /// Convert to a raw `{item.name}` with `struct_size` initialised.\n")
        out.append(f"    #[must_use]\n    pub fn to_c(&self) -> sys::{item.name} {{\n")
        out.append(f"        sys::{item.name} {{\n")
        for fld in plain:
            val = f"self.{fld.name}.to_c()" if _nested_numbers(api, fld) else f"self.{fld.name}"
            out.append(f"            {fld.name}: {val},\n")
        if len(plain) < len(item.fields):
            out.append(f"            ..sys::{item.name}::default()\n")
        out.append("        }\n    }\n")
    out.append("}\n")
    return "".join(out)


def _safe_call_parts(api: Api, fn: Function) -> tuple[list[str], list[str], Struct | None]:
    setup: list[str] = []
    args: list[str] = ["self.handle"]
    out_struct: Struct | None = None
    for param in fn.params[1:]:
        if param.mode == "error":
            setup.append("let mut c_err: *mut sys::VmafxError = std::ptr::null_mut();")
            args.append("&raw mut c_err")
        elif param.mode == "out" and api.is_struct(param.type):
            out_struct = api.struct(param.type)
            setup.append(f"let mut out = sys::{param.type}::default();")
            args.append("&raw mut out")
        elif param.type == "cstr":
            c_var = f"c_{param.name}"
            setup.append(
                f'let {c_var} = into_c_string({param.name}, "{fn.name}", "{param.name}")?;'
            )
            args.append(f"{c_var}.as_ptr()")
        else:
            args.append(param.name)
    return setup, args, out_struct


def _safe_context_method(api: Api, fn: Function) -> str:
    setup, args, out_struct = _safe_call_parts(api, fn)
    in_params = [
        f"{p.name}: {'&str' if p.type == 'cstr' else SAFE_TYPES[p.type]}"
        for p in fn.params[1:]
        if p.mode not in ("error", "out", "out_handle")
    ]
    name = _method_name(fn)
    ret_type = short(out_struct.name) if out_struct else "()"
    sig_params = ", ".join(["&self", *in_params])
    single_sig = f"    pub fn {name}({sig_params}) -> Result<{ret_type}> {{"
    out = [
        "\n",
        _doc_lines(fn.doc, "    "),
        "    ///\n    /// # Errors\n    /// Returns [`Error`] on a non-OK status.\n",
    ]
    if len(single_sig) <= MAX_LINE:
        out.append(single_sig + "\n")
    else:
        inner = "".join(f"        {p},\n" for p in ["&self", *in_params])
        out.append(f"    pub fn {name}(\n{inner}    ) -> Result<{ret_type}> {{\n")
    out.extend(f"        {line}\n" for line in setup)
    out.append(
        "        // SAFETY: `self.handle`, C string pointers, and out-pointers are valid for this call.\n"
        "        unsafe {\n"
    )
    call = f"sys::{fn.name}({', '.join(args)})"
    if len(f"            let status = {call};") <= MAX_LINE:
        out.append(f"            let status = {call};\n")
    elif len(f"                {call};") <= MAX_LINE:
        out.append(f"            let status =\n                {call};\n")
    else:
        inner_args = "".join(f"                {a},\n" for a in args)
        out.append(f"            let status = sys::{fn.name}(\n{inner_args}            );\n")
    if out_struct is not None:
        rec = short(out_struct.name)
        out.append(f'            check_status(status, c_err, "{fn.name}")?;\n        }}\n')
        out.append(f"        Ok({rec}::from_c(out))\n    }}\n")
    else:
        out.append(f'            check_status(status, c_err, "{fn.name}")\n        }}\n    }}\n')
    return "".join(out)


def _safe_library_function(fn: Function) -> str:
    outs = [p for p in fn.params if p.mode == "out"]
    ins = [p for p in fn.params if p.mode != "out"]
    params = ", ".join(
        f"{p.name}: {'&str' if p.type == 'cstr' else SAFE_TYPES[p.type]}" for p in ins
    )
    name = _library_method_name(fn)
    setup: list[str] = []
    args: list[str] = []
    for param in fn.params:
        if param.mode == "out":
            setup.append(f"let mut {param.name}: {SYS_SCALARS[param.type]} = 0;")
            args.append(f"&raw mut {param.name}")
        elif param.type == "cstr":
            c_var = f"c_{param.name}"
            setup.append(
                f"let {c_var} = if {param.name}.is_empty() {{\n"
                "        None\n"
                "    } else {\n"
                f"        CString::new({param.name}).ok()\n"
                "    };"
            )
            setup.append(
                f"let {c_var}_ptr = {c_var}.as_ref().map_or(std::ptr::null(), |s| s.as_ptr());"
            )
            args.append(f"{c_var}_ptr")
        elif param.type == "status":
            args.append(f"{param.name} as sys::VmafxStatus")
        else:
            args.append(param.name)
    out = [f"\n{_doc_lines(fn.doc)}#[must_use]\n"]
    call = f"sys::{fn.name}({', '.join(args)})"
    if fn.returns == "cstr":
        out.append(f"pub fn {name}({params}) -> String {{\n")
        out.extend(f"    {line}\n" for line in setup)
        out.append(
            "    // SAFETY: All scalar arguments and C string pointers are valid for this call.\n"
        )
        out.append(f"    let ptr = unsafe {{ {call} }};\n")
        out.append("    c_str_ptr_to_string(ptr)\n}\n")
        return "".join(out)
    ret_types = ", ".join(SAFE_TYPES[p.type] for p in outs)
    ret_sig = f"({ret_types})" if len(outs) != 1 else ret_types
    ret_vals = ", ".join(p.name for p in outs)
    ret_expr = f"({ret_vals})" if len(outs) != 1 else ret_vals
    out.append(f"pub fn {name}({params}) -> {ret_sig} {{\n")
    out.extend(f"    {line}\n" for line in setup)
    out.append("    // SAFETY: All out-pointers and scalar arguments are valid for this call.\n")
    out.append(f"    unsafe {{ {call} }};\n")
    out.append(f"    {ret_expr}\n}}\n")
    return "".join(out)


def safe_text(api: Api) -> str:
    """Render bindings/rust/vmafx/src/api_gen.rs."""
    lib_fns = library_functions(api)
    _refuse_collisions("Library", lib_fns, _library_method_name)
    parts = [HEADER, _SAFE_PREAMBLE, _safe_constants(api), _SAFE_ERROR]
    if api.is_handle(CONTEXT):
        parts.append(_SAFE_CONTEXT_HELPERS)
    parts += [_safe_record_struct(api, item) for item in api.structs]
    if api.is_handle(CONTEXT):
        methods = context_methods(api)
        _refuse_collisions("Context", methods, _method_name)
        parts.append(_SAFE_CONTEXT_HEAD)
        parts += [_safe_context_method(api, fn) for fn in methods]
        parts.append(_SAFE_CONTEXT_DROP)
    parts += [_safe_library_function(fn) for fn in lib_fns]
    return "".join(parts)
