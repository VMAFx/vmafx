def _variant(name: str) -> str:
    words = {"NOMEM": "NoMem", "NOTSUP": "NotSup", "NOTFOUND": "NotFound"}
    return "".join(words.get(word, word.title()) for word in name.removeprefix("VMAFX_").split("_"))


def _doc(text: str) -> str:
    """Quote snake_case identifiers while preserving existing inline code."""
    parts = text.split("`")
    for index in range(0, len(parts), 2):
        parts[index] = re.sub(
            r"\b[A-Za-z][A-Za-z0-9]*(?:_[A-Za-z0-9]+)+(?:\(\))?",
            r"`\g<0>`",
            parts[index],
        )
    return "`".join(parts)


def _doc_lines(text: str, indent: str = "") -> str:
    width = 96 - len(indent)
    return "".join(f"{indent}/// {line}\n" for line in textwrap.wrap(_doc(text), width=width))


def status_text(api: Api) -> str:
    """Render the safe crate's status_gen module without changing bindgen."""
    out = [
        HEADER,
        "//! Stable `VMAFx` API status codes from `core/api/vmafx.toml`.\n\n",
        "/// Result of an API call: zero success, positive information, negative failure.\n",
        "#[derive(Clone, Copy, Debug, Eq, PartialEq)]\n#[repr(i32)]\n#[non_exhaustive]\n",
        "pub enum Status {\n",
    ]
    for status in api.statuses:
        out.append(_doc_lines(status.doc, "    "))
        out.append(f"    {_variant(status.name)} = {status.value},\n")
    out.append("}\n\nimpl Status {\n")
    out.append("    /// Decode a raw API code; unknown values return `None`.\n")
    out.append("    #[must_use]\n    pub const fn from_raw(value: i32) -> Option<Self> {\n")
    out.append("        match value {\n")
    for status in api.statuses:
        out.append(f"            {status.value} => Some(Self::{_variant(status.name)}),\n")
    out.append("            _ => None,\n        }\n    }\n\n")
    out.append('    /// Return the definition\'s symbolic errno name (`"0"` for success).\n')
    out.append("    ///\n    /// Names are platform independent; `Pending` maps to `EAGAIN`.\n")
    out.append("    #[must_use]\n    pub const fn errno(self) -> &'static str {\n")
    out.append("        match self {\n")
    errnos: dict[str, list[str]] = {}
    for status in api.statuses:
        errnos.setdefault(status.errno, []).append(f"Self::{_variant(status.name)}")
    for errno, variants in errnos.items():
        out.append(f'            {" | ".join(variants)} => "{errno}",\n')
    out.append("        }\n    }\n\n")
    out.append("    /// Return the canonical API name from the definition.\n")
    out.append("    #[must_use]\n    pub const fn as_str(self) -> &'static str {\n")
    out.append("        match self {\n")
    for status in api.statuses:
        out.append(f'            Self::{_variant(status.name)} => "{status.name}",\n')
    out.append("        }\n    }\n}\n")
    return "".join(out)


def _sys_type(api: Api, name: str, *, const: bool = False) -> str:
    kind = typesys.kind(api, name)
    if kind == "struct":
        return name
    if kind == "handle":
        return f"*const {name}" if const else f"*mut {name}"
    if kind == "foreign":
        return f"*mut crate::{name.split(':', 1)[1]}"
    if kind == "callback":
        return name
    return SYS_SCALARS[name]


def _sys_field_default(api: Api, fld: Field) -> str:
    if fld.name == "struct_size":
        return "core::mem::size_of::<Self>() as u32"
    kind = typesys.kind(api, fld.type)
    if kind == "struct":
        elem = f"{fld.type}::default()"
    elif kind == "callback":
        elem = "None"
    elif (kind == "handle" and fld.const) or fld.type in ("cptr", "cstr"):
        elem = "core::ptr::null()"
    elif kind == "handle" or fld.type == "ptr":
        elem = "core::ptr::null_mut()"
    elif fld.type in ("f32", "f64"):
        elem = "0.0"
    else:
        elem = "0"
    return f"[{elem}; {fld.count}]" if fld.count else elem


def _sys_param_type(api: Api, param: Param) -> str:
    if param.mode == "error":
        return "*mut *mut VmafxError"
    if param.mode == "out_handle":
        return f"*mut *mut {param.type}"
    if param.mode == "out":
        return f"*mut {_sys_type(api, param.type)}"
    if param.mode == "in_const":
        return f"*const {param.type}"
    if typesys.kind(api, param.type) == "struct":
        return f"*const {param.type}"
    return _sys_type(api, param.type)


def _sys_return(returns: str) -> str:
    if returns == "void":
        return ""
    if returns.startswith("handle:"):
        return f" -> *mut {returns.split(':', 1)[1]}"
    if returns.startswith("foreign:"):
        return f" -> *mut crate::{returns.split(':', 1)[1]}"
    return f" -> {SYS_SCALARS[returns]}"


def _sys_constants(api: Api) -> str:
    major, minor, patch = api.abi_version
    out = [
        "/// Stable `VMAFx` status code (`int32_t`).\n",
        "pub type VmafxStatus = i32;\n\n",
        f"pub const VMAFX_ABI_VERSION_MAJOR: u32 = {major};\n",
        f"pub const VMAFX_ABI_VERSION_MINOR: u32 = {minor};\n",
        f"pub const VMAFX_ABI_VERSION_PATCH: u32 = {patch};\n\n",
    ]
    for status in api.statuses:
        out.append(f"pub const {status.name}: VmafxStatus = {status.value};\n")
    for item in api.enums:
        out.append(f"\npub type {item.name} = u32;\n")
        for val in item.values:
            out.append(f"pub const {val.name}: {item.name} = {val.value};\n")
    for flags in api.flags:
        rust_type = SYS_SCALARS[flags.type]
        out.append(f"\npub type {flags.name} = {rust_type};\n")
        for bit in flags.bits:
            out.append(f"pub const {bit.name}: {flags.name} = 1 << {bit.bit};\n")
    return "".join(out)


def _sys_handles_and_callbacks(api: Api) -> str:
    out: list[str] = []
    for handle in api.handles:
        out.append(f"\n#[repr(C)]\npub struct {handle.name} {{\n    _private: [u8; 0],\n}}\n")
    safety = "C callback function-pointer signature from core/api/vmafx.toml."
    for cb in api.callbacks:
        params = ", ".join(_sys_param_type(api, p) for p in cb.params)
        ret = _sys_return(cb.returns)
        fn_sig = f'unsafe extern "C" fn({params}){ret}'
        single = f"pub type {cb.name} = Option<{fn_sig}>;"
        if len(single) <= MAX_LINE:
            out.append(f"\n// SAFETY: {safety}\n{single}\n")
        else:
            out.append(
                f"\npub type {cb.name} = Option<\n    // SAFETY: {safety}\n    {fn_sig},\n>;\n"
            )
    return "".join(out)


def _sys_struct(api: Api, item: Struct) -> str:
    derivable = not item.sized and not any(
        "*" in _sys_type(api, fld.type, const=fld.const) for fld in item.fields
    )
    derives = "Clone, Copy, Debug, Default" if derivable else "Clone, Copy, Debug"
    out = [f"\n#[repr(C)]\n#[derive({derives})]\npub struct {item.name} {{\n"]
    for fld in item.fields:
        base = _sys_type(api, fld.type, const=fld.const)
        ftype = f"[{base}; {fld.count}]" if fld.count else base
        out.append(f"    pub {fld.name}: {ftype},\n")
    out.append("}\n")
    if derivable:
        return "".join(out)
    out.append(f"\nimpl Default for {item.name} {{\n    fn default() -> Self {{\n        Self {{\n")
    for fld in item.fields:
        out.append(f"            {fld.name}: {_sys_field_default(api, fld)},\n")
    out.append("        }\n    }\n}\n")
    return "".join(out)


def _sys_layout_assertions(api: Api) -> str:
    out = ["\n// Compile-time struct layout assertions against the API definition.\n"]
    for name, lay in layouts(api).items():
        expr = (
            f"core::mem::size_of::<{name}>() == {lay.size} "
            f"&& core::mem::align_of::<{name}>() == {lay.align}"
        )
        if len(f"const _: () = assert!({expr});") <= MAX_LINE:
            out.append(f"const _: () = assert!({expr});\n")
        elif len(f"    assert!({expr});") <= MAX_LINE:
            out.append(f"const _: () =\n    assert!({expr});\n")
        elif len(f"    {expr}") < MAX_LINE:
            out.append(f"const _: () = assert!(\n    {expr}\n);\n")
        else:
            out.append(
                "const _: () = assert!(\n"
                f"    core::mem::size_of::<{name}>() == {lay.size}\n"
                f"        && core::mem::align_of::<{name}>() == {lay.align}\n"
                ");\n"
            )
    return "".join(out)


def _sys_functions(api: Api) -> list[Function]:
    wanted = (
        {fn.name for fn in context_methods(api)}
        | {fn.name for fn in library_functions(api)}
        | SYS_EXTRA_FUNCTIONS
    )
    return [fn for fn in api.functions if fn.name in wanted]


def _sys_extern_block(api: Api) -> str:
    fns = _sys_functions(api)
    if not fns:
        return ""
    out = [
        "\n// SAFETY: C function declarations generated from core/api/vmafx.toml and linked from libvmafx.\n",
        'unsafe extern "C" {\n',
    ]
    for fn in fns:
        params = [f"{p.name}: {_sys_param_type(api, p)}" for p in fn.params]
        ret = _sys_return(fn.returns)
        single = f"    pub fn {fn.name}({', '.join(params)}){ret};"
        if len(single) <= MAX_LINE:
            out.append(single + "\n")
        else:
            inner = "".join(f"        {p},\n" for p in params)
            out.append(f"    pub fn {fn.name}(\n{inner}    ){ret};\n")
    out.append("}\n")
    return "".join(out)


def sys_text(api: Api) -> str:
    """Render bindings/rust/vmafx-sys/src/vmafx_api_gen.rs."""
    parts = [
        HEADER,
        "//! Raw FFI declarations for the `VMAFx` C API (`core/api/vmafx.toml`).\n\n",
        "use core::ffi::{c_char, c_void};\n\n",
        _sys_constants(api),
        _sys_handles_and_callbacks(api),
    ]
    parts += [_sys_struct(api, item) for item in api.structs]
    if api.structs:
        parts.append(_sys_layout_assertions(api))
    parts.append(_sys_extern_block(api))
    return "".join(parts)


