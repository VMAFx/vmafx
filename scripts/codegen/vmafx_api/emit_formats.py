"""Surfaces generated from the input format table (ADR-2145).

- `core/src/vmafx/import_layouts_gen.h`: the layout table the import reads.
- `core/api/generated/vmafx_ffmpeg_formats.h`: `AV_PIX_FMT_*` lists for the
  FFmpeg filter (host frames, and the software formats of CUDA / HIP frames).
- `core/api/generated/vmafx_gstreamer_formats.h`: GStreamer format lists and
  caps strings for the element.
- `docs/usage/pixel-formats.md`: the table for readers.

A list is the rows that qualify, in table order; nothing here is typed twice.
"""

from __future__ import annotations

from .format_table import PIXEL_FORMAT_PREFIX
from .model import Api, PixelFormat

NOTICE = (
    "GENERATED by scripts/codegen/vmafx-api.py from core/api/vmafx.toml "
    "([[pixel_formats]], ADR-2145).\n"
    "Do not edit: change the definition and run "
    "`python3 scripts/codegen/vmafx-api.py --write`."
)
PACKED_CONSTANT = {
    "none": "NONE",
    "yuyv": "YUYV",
    "uyv4": "UYV4",
    "xvyu2101010": "XVYU2101010",
    "v210": "V210",
    "rgb": "RGB",
}
FFMPEG_MACRO_OVERRIDE = {"gray": "GRAY8"}
SPDX = "SPDX-" + "License-Identifier: EUPL-1.2"  # split: not this file's header


def _c_head(brief: str) -> list[str]:
    return [
        "/**",
        " *",
        " *  Copyright 2026 Lusoris",
        " *",
        f" * {SPDX}",
        " */",
        "",
        "/*",
        *[f" * {line}" for line in NOTICE.splitlines()],
        " *",
        f" * {brief}",
        " */",
        "",
    ]


def _bool(value: bool) -> str:
    return "true" if value else "false"


def _row(row: PixelFormat) -> str:
    elem = ", ".join(f"{e}u" for e in row.elem)
    return (
        f"    {{.pix_fmt = {row.enum},\n"
        f"     .planar_fmt = {row.planar},\n"
        f"     .n_planes = {row.planes}u,\n"
        f"     .bpc_min = {row.bpc[0]}u,\n"
        f"     .bpc_max = {row.bpc[1]}u,\n"
        f"     .shift = {row.shift}u,\n"
        f"     .interleaved = {_bool(row.interleaved)},\n"
        f'     .name = "{row.name}",\n'
        f"     .packed = VMAFX_IMPORT_PACKED_{PACKED_CONSTANT[row.packing]},\n"
        f"     .elem = {{{elem}}},\n"
        f"     .msb = {_bool(row.msb)},\n"
        f"     .rgb_elems = {row.rgb_elems}u,\n"
        f"     .needs_statement = {_bool(row.needs_statement)}}},"
    )


def import_layouts(api: Api) -> str:
    lines = _c_head("The import layout table: one row per VmafxPixelFormat (frame_import.c).")
    lines += [
        "#ifndef VMAFX_IMPORT_LAYOUTS_GEN_H",
        "#define VMAFX_IMPORT_LAYOUTS_GEN_H",
        "",
        '#include "vmafx/import_layout.h"',
        '#include "vmafx/types.h"',
        "",
        "/* clang-format off */",
        "static const VmafxImportLayout vmafx_import_layouts[] = {",
        *[_row(row) for row in api.pixel_formats],
        "};",
        "/* clang-format on */",
        "",
        "#define VMAFX_N_IMPORT_LAYOUTS (sizeof(vmafx_import_layouts) / sizeof(vmafx_import_layouts[0]))",
        "",
        "#endif /* VMAFX_IMPORT_LAYOUTS_GEN_H */",
    ]
    return "\n".join(lines) + "\n"


def ffmpeg_macro(name: str) -> str:
    return "AV_PIX_FMT_" + FFMPEG_MACRO_OVERRIDE.get(name, name.upper())


def _rows(api: Api, device: str | None, rgb: bool) -> list[PixelFormat]:
    return [
        row
        for row in api.pixel_formats
        if (device is None or device in row.devices) and (row.layout == "rgb") == rgb
    ]


def _ffmpeg_names(rows: list[PixelFormat]) -> list[str]:
    return [name for row in rows for _, name in sorted(row.ffmpeg.items())]


def _gst_names(rows: list[PixelFormat]) -> list[str]:
    return [name for row in rows for _, name in sorted(row.gstreamer.items())]


def _list_macro(name: str, entries: list[str]) -> list[str]:
    if not entries:
        return [f"#define {name}", ""]
    body = " \\\n".join(f"    {entry}," for entry in entries)
    return [f"#define {name} \\\n{body.removesuffix(',')}", ""]


def ffmpeg_formats(api: Api) -> str:
    lines = _c_head(
        "Pixel formats of the `vmafx` FFmpeg filter. Use as `static const enum AVPixelFormat\n"
        " * pix_fmts[] = { VMAFX_FFMPEG_YUV_PIX_FMTS, AV_PIX_FMT_NONE };`. The RGB lists are\n"
        " * accepted only when the filter is given the matrix, range and transfer of the\n"
        " * conversion (ADR-2146); a hardware list is what the library imports on that device,\n"
        " * to be intersected with the formats FFmpeg's own hwcontext allows."
    )
    lines += ["#ifndef VMAFX_FFMPEG_FORMATS_H", "#define VMAFX_FFMPEG_FORMATS_H", ""]
    lines += ["#include <libavutil/pixfmt.h>", "", "/* clang-format off */", ""]
    for label, device in (
        ("PIX_FMTS", None),
        ("CUDA_SW_FORMATS", "cuda"),
        ("HIP_SW_FORMATS", "hip"),
    ):
        for kind, rgb in (("YUV", False), ("RGB", True)):
            names = [ffmpeg_macro(n) for n in _ffmpeg_names(_rows(api, device, rgb))]
            lines += _list_macro(f"VMAFX_FFMPEG_{kind}_{label}", names)
    lines += ["/* clang-format on */", "", "#endif /* VMAFX_FFMPEG_FORMATS_H */"]
    return "\n".join(lines) + "\n"


def gstreamer_formats(api: Api) -> str:
    lines = _c_head(
        "Formats of the `vmafx` GStreamer element: `VMAFX_GST_FORMATS_*` are comma-separated\n"
        " * lists for a caps `format` field, `VMAFX_GST_CAPS_*` whole caps strings. The RGB lists\n"
        " * are accepted only with a stated matrix, range and transfer (ADR-2146)."
    )
    lines += ["#ifndef VMAFX_GSTREAMER_FORMATS_H", "#define VMAFX_GSTREAMER_FORMATS_H", ""]
    lines += ["/* clang-format off */", ""]
    for label, device in (("HOST", None), ("CUDA", "cuda"), ("HIP", "hip")):
        for kind, rgb in (("YUV", False), ("RGB", True)):
            names = _gst_names(_rows(api, device, rgb))
            joined = ", ".join(names)
            lines += [f'#define VMAFX_GST_FORMATS_{label}_{kind} "{joined}"', ""]
            lines += [
                f"#define VMAFX_GST_CAPS_{label}_{kind} \\",
                f'    "video/x-raw, format = (string) {{ " VMAFX_GST_FORMATS_{label}_{kind} " }}"',
                "",
            ]
    lines += ["/* clang-format on */", "", "#endif /* VMAFX_GSTREAMER_FORMATS_H */"]
    return "\n".join(lines) + "\n"


def _depth_list(names: dict[int, str]) -> str:
    return ", ".join(f"{d}: `{n}`" for d, n in sorted(names.items())) or "none"


def formats_page(api: Api) -> str:
    head = [
        "<!-- markdownlint-disable MD013 -->",
        "<!-- " + NOTICE.replace("\n", " ") + " -->",
        "# Input pixel formats (generated)",
        "",
        "The pixel formats VMAFx reads, from the table `[[pixel_formats]]` of",
        "[`core/api/vmafx.toml`](../../core/api/vmafx.toml)",
        "([ADR-2145](../adr/2145-vmafx-input-format-table.md)). Every layout is",
        "converted to the planar frame in the second column with nothing but a gather,",
        "a shift and a mask, so a frame scores bit for bit as the same samples in",
        "planar form; the RGB layouts are converted to Y'CbCr only with a stated matrix,",
        "range and transfer ([ADR-2146](../adr/2146-vmafx-rgb-input-explicit-matrix.md)).",
        "The FFmpeg and GStreamer names are the lists the filter and the element",
        "take; the devices column names the backends that import the layout on the",
        "device without a host copy.",
        "",
        "| `VmafxPixelFormat` | Frame made | Layout | Bits | Chroma siting | Devices |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    rows = [
        f"| `{r.enum.removeprefix(PIXEL_FORMAT_PREFIX)}` | `{r.planar.removeprefix(PIXEL_FORMAT_PREFIX)}` "
        f"| {r.layout.replace('_', '-')}{', statement required' if r.needs_statement else ''} "
        f"| {r.bpc[0]}{'' if r.bpc[0] == r.bpc[1] else f' to {r.bpc[1]}'} | {r.siting} "
        f"| {', '.join(r.devices)} |"
        for r in api.pixel_formats
    ]
    names = [
        "",
        "## Names on each surface",
        "",
        "| Format | FFmpeg (bits: name) | GStreamer (bits: name) |",
        "| --- | --- | --- |",
        *[
            f"| `{r.name}` | {_depth_list(r.ffmpeg)} | {_depth_list(r.gstreamer)} |"
            for r in api.pixel_formats
        ],
        "",
    ]
    return "\n".join([*head, *rows, *names])


def outputs(api: Api) -> list[tuple[str, str]]:
    """(path, text) of every file generated from the format table."""
    if not api.pixel_formats:
        return []
    return [
        ("core/src/vmafx/import_layouts_gen.h", import_layouts(api)),
        ("core/api/generated/vmafx_ffmpeg_formats.h", ffmpeg_formats(api)),
        ("core/api/generated/vmafx_gstreamer_formats.h", gstreamer_formats(api)),
        ("docs/usage/pixel-formats.md", formats_page(api)),
    ]
