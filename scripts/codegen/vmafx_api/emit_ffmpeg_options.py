"""FFmpeg AVOption table of the `vmafx` filter (design section 5.2, WP9 consumes it).

`ffmpeg-patches/src/vf_vmafx_options.h` declares:

- `VMAFX_FILTER_OPTION_FIELDS`: the context fields the options write, for the
  filter's private context struct;
- `VMAFX_FILTER_OPTIONS(CTX, FLAGS)`: the AVOption entries, aliases (upstream
  names such as `n_threads`) pointing at the same field, enumerated and flags
  options with their AV_OPT_TYPE_CONST values;
- `VMAFX_OPT_<NAME>_VALUES`: an initializer list of an enumerated or flags
  option's value names, indexed by the integer (enum) or bit (flags) stored.

The header is compiled into an FFmpeg filter, so it carries FFmpeg's licence
like the fork's other FFmpeg sources. An option whose default is the library's
(`default_macro`) stores NULL, and the filter asks the library at init.
"""

