def _suffix(name: str) -> str:
    words = {
        "OK": "OK",
        "IO": "IO",
        "ABI": "ABI",
        "NOMEM": "NoMem",
        "NOTSUP": "NotSup",
        "NOTFOUND": "NotFound",
    }
    return "".join(words.get(word, word.title()) for word in name.removeprefix("VMAFX_").split("_"))


def _camel(name: str) -> str:
    return _suffix(name.upper())


def _lower_first(name: str) -> str:
    return name[:1].lower() + name[1:] if name else name


def _c_field(name: str) -> str:
    return f"_{name}" if name in GO_KEYWORDS else name


def _align_rows(rows: list[tuple[str, str]], indent: str) -> str:
    width = max((len(left) for left, _ in rows), default=0)
    return "".join(
        f"{indent}{left}{' ' * (width - len(left) + 1)}{right}\n" for left, right in rows
    )


def _sentinel(name: str) -> str:
    return "Err" + _suffix(name.removeprefix("VMAFX_E_"))


def status_text(api: Api) -> str:
    """Render pkg/vmafx/status_gen.go; no cgo or native library dependency."""
    out = [
        "// Copyright 2026 Lusoris\n// SPDX-License-Identifier: EUPL-1.2\n\n",
        "// Code generated by scripts/codegen/vmafx-api.py; DO NOT EDIT.\n\n",
        'package vmafx\n\nimport (\n\t"errors"\n\t"fmt"\n\t"os"\n\t"syscall"\n)\n\n',
        "// Status is a stable VMAFx API result: zero success, positive information, negative failure.\n",
        "type Status int32\n",
    ]
    wraps = {
        "VMAFX_E_INVALID": "os.ErrInvalid",
        "VMAFX_E_NOTFOUND": "os.ErrNotExist",
        "VMAFX_E_NOTSUP": "errors.ErrUnsupported",
    }
    for status in api.statuses:
        name = "Status" + _suffix(status.name)
        out.append(f"\n// {name}: {status.doc}\nconst {name} Status = {status.value}\n")
        if status.value < 0:
            sentinel = _sentinel(status.name)
            message = json.dumps(f"vmafx: {status.name}")
            value = (
                f"fmt.Errorf({json.dumps(f'vmafx: {status.name}: %w')}, {wraps[status.name]})"
                if status.name in wraps
                else f"errors.New({message})"
            )
            out.append(f"\n// {sentinel}: {status.doc}\nvar {sentinel} = {value}\n")
    out.append("\n// String returns the canonical API name, or Status(n) for an unknown code.\n")
    out.append("func (s Status) String() string {\n\tswitch s {\n")
    for status in api.statuses:
        out.append(f'\tcase Status{_suffix(status.name)}:\n\t\treturn "{status.name}"\n')
    out.append('\tdefault:\n\t\treturn fmt.Sprintf("Status(%d)", s)\n\t}\n}\n')
    out.append("\n// Errno returns the platform errno, or zero for an unknown code.\n")
    out.append("// Pending maps to EAGAIN; use Err to distinguish failures.\n")
    out.append("func (s Status) Errno() syscall.Errno {\n\tswitch s {\n")
    for status in api.statuses:
        errno = "0" if status.errno == "0" else f"syscall.{status.errno}"
        out.append(f"\tcase Status{_suffix(status.name)}:\n\t\treturn {errno}\n")
    out.append("\tdefault:\n\t\treturn 0\n\t}\n}\n")
    out.append(
        "\n// Err returns nil for nonnegative codes and a sentinel for each known failure.\n"
    )
    out.append("func (s Status) Err() error {\n\tif s >= 0 {\n\t\treturn nil\n\t}\n\tswitch s {\n")
    for status in api.statuses:
        if status.value < 0:
            out.append(
                f"\tcase Status{_suffix(status.name)}:\n\t\treturn {_sentinel(status.name)}\n"
            )
    out.append('\tdefault:\n\t\treturn fmt.Errorf("vmafx: unknown status %d", s)\n\t}\n}\n')
    return "".join(out)


def _api_header(api: Api) -> str:
    includes = [f"#include <{api.umbrella.path}>\n"]
    includes += [f"#include <{h.path}>\n" for h in api.headers if h.group == "optional"]
    return (
        "// Copyright 2026 Lusoris\n"
        "// " + "SPDX-" + "License-Identifier: EUPL-1.2\n\n"  # split: not this file's header
        "// Code generated by scripts/codegen/vmafx-api.py; DO NOT EDIT.\n\n"
        "//go:build cgo\n\n"
        "package vmafx\n\n"
        "/*\n"
        "#cgo CFLAGS: -I${SRCDIR}/../../core/include\n"
        "// No #cgo pkg-config or -lvmafx fallback: callers pass CGO_LDFLAGS pointing at a\n"
        "// VMAFx build directory (see .github/workflows/go-ci.yml and ADR-1125) so that\n"
        "// `go vet` and static analysis run against in-tree headers without a pre-built\n"
        "// shared library and `go test` / `go build` fail closed unless a library path is\n"
        "// explicitly configured.\n"
        "#include <stdlib.h>\n" + "".join(includes) + '*/\nimport "C"\n\n'
        'import (\n\t"errors"\n\t"fmt"\n\t"unsafe"\n)\n'
    )


def _abi_and_enums(api: Api) -> str:
    major, minor, patch = api.abi_version
    out = [
        "\n// ABI version of the VMAFx definition this binding was generated from.\n",
        f"const ABIVersionMajor uint32 = {major}\n",
        f"const ABIVersionMinor uint32 = {minor}\n",
        f"const ABIVersionPatch uint32 = {patch}\n",
    ]
    for item in api.enums:
        out.append(f"\n// {item.name} values.\n")
        for val in item.values:
            out.append(f"const {_suffix(val.name)} uint32 = {val.value}\n")
    for flags in api.flags:
        go_type = GOTYPES[flags.type]
        out.append(f"\n// {flags.name} bit values.\n")
        for bit in flags.bits:
            out.append(f"const {_suffix(bit.name)} {go_type} = 1 << {bit.bit}\n")
    return "".join(out)


def _layout_assertions(api: Api) -> str:
    safety = (
        "// SAFETY: unsafe.Sizeof and unsafe.Alignof are evaluated at compile time "
        "and dereference nothing.\n"
    )
    out = ["\n// Compile-time struct layout assertions against the API definition.\n"]
    for name, lay in layouts(api).items():
        out.append(f"{safety}var _ [{lay.size} - unsafe.Sizeof(C.{name}{{}})]byte\n\n")
        out.append(f"{safety}var _ [unsafe.Sizeof(C.{name}{{}}) - {lay.size}]byte\n\n")
        out.append(f"{safety}var _ [{lay.align} - unsafe.Alignof(C.{name}{{}})]byte\n\n")
        out.append(f"{safety}var _ [unsafe.Alignof(C.{name}{{}}) - {lay.align}]byte\n\n")
    return "".join(out).rstrip("\n") + "\n"


_ERROR_TYPE = (
    "\n// ErrPending is wrapped by *Error when a requested score is not final yet (VMAFX_PENDING).\n"
    'var ErrPending = errors.New("vmafx: VMAFX_PENDING")\n\n'
    "// Error represents a non-OK VMAFx API result with structured diagnostics.\n"
    "type Error struct {\n"
    "\tFunction string\n"
    "\tStatus   Status\n"
    "\tMessage  string\n"
    "\tSubject  string\n"
    "\tErrno    int32\n"
    "}\n\n"
    "func (e *Error) Error() string {\n"
    '\tif e.Subject != "" {\n'
    '\t\treturn fmt.Sprintf("%s: %s: %s [%s]", e.Function, e.Status, e.Message, e.Subject)\n'
    "\t}\n"
    '\tif e.Message != "" {\n'
    '\t\treturn fmt.Sprintf("%s: %s: %s", e.Function, e.Status, e.Message)\n'
    "\t}\n"
    '\treturn fmt.Sprintf("%s: %s", e.Function, e.Status)\n'
    "}\n\n"
    "func (e *Error) Unwrap() error {\n"
    "\tif e.Status == StatusPending {\n"
    "\t\treturn ErrPending\n"
    "\t}\n"
    "\treturn e.Status.Err()\n"
    "}\n"
)

_FREE_CSTRING = (
    "\nfunc freeCString(p *C.char) {\n"
    "\t// SAFETY: p was allocated by C.CString and is freed once after the C call returns.\n"
    "\tC.free(unsafe.Pointer(p))\n"
    "}\n"
)

_CHECK_STATUS = (
    "\nfunc checkStatus(status Status, cErr *C.VmafxError, function string) error {\n"
    "\tif status == StatusOK {\n"
    "\t\treturn nil\n"
    "\t}\n"
    "\tvar message, subject string\n"
    "\tvar errnoVal int32\n"
    "\tif cErr != nil {\n"
    "\t\tmessage = C.GoString(C.vmafx_error_message(cErr))\n"
    "\t\tsubject = C.GoString(C.vmafx_error_subject(cErr))\n"
    "\t\terrnoVal = int32(C.vmafx_error_errno(cErr))\n"
    "\t\tC.vmafx_error_free(cErr)\n"
    "\t}\n"
    "\treturn &Error{\n"
    "\t\tFunction: function,\n"
    "\t\tStatus:   status,\n"
    "\t\tMessage:  message,\n"
    "\t\tSubject:  subject,\n"
    "\t\tErrno:    errnoVal,\n"
    "\t}\n"
    "}\n"
)


def _error_section(api: Api) -> str:
    need_cstr = api.is_handle(CONTEXT) or any(
        p.type == "cstr" for fn in library_functions(api) for p in fn.params
    )
    out = [_ERROR_TYPE]
    if need_cstr:
        out.append(_FREE_CSTRING)
    if api.is_handle(CONTEXT):
        out.append(_CHECK_STATUS)
    return "".join(out)


def _go_record_field(api: Api, fld: Field) -> tuple[str, str, bool] | None:
    """(go_type, from_c_expr, is_array) for a record field, or None if C-only."""
    kind = typesys.kind(api, fld.type)
    raw = f"raw.{_c_field(fld.name)}"
    if kind == "struct":
        rec = short(fld.type)
        conv = f"{_lower_first(rec)}FromC"
        if fld.count:
            return f"[{fld.count}]{rec}", f"{conv}({raw}[i])", True
        return rec, f"{conv}({raw})", False
    if kind != "scalar" or fld.type in POINTERS:
        return None
    go_type = GOTYPES[fld.type]
    if fld.count:
        return f"[{fld.count}]{go_type}", f"{go_type}({raw}[i])", True
    expr = f"C.GoString({raw})" if fld.type == "cstr" else f"{go_type}({raw})"
    return go_type, expr, False


def _from_c_func(item: Struct, kept: list[tuple[Field, tuple[str, str, bool]]]) -> str:
    rec = short(item.name)
    fn_name = f"{_lower_first(rec)}FromC"
    scalars = [(f"{_camel(f.name)}:", f"{v[1]},") for f, v in kept if not v[2]]
    arrays = [(f, v[1]) for f, v in kept if v[2]]
    if not arrays:
        body = _align_rows(scalars, "\t\t")
        return f"\nfunc {fn_name}(raw C.{item.name}) {rec} {{\n\treturn {rec}{{\n{body}\t}}\n}}\n"
    lines = [f"\nfunc {fn_name}(raw C.{item.name}) {rec} {{\n"]
    if scalars:
        lines.append(f"\tout := {rec}{{\n{_align_rows(scalars, '\t\t')}\t}}\n")
    else:
        lines.append(f"\tvar out {rec}\n")
    for fld, expr in arrays:
        lines.append(f"\tfor i := 0; i < {fld.count}; i++ {{\n")
        lines.append(f"\t\tout.{_camel(fld.name)}[i] = {expr}\n\t}}\n")
    lines.append("\treturn out\n}\n")
    return "".join(lines)


def _to_c_func(api: Api, item: Struct, fields: list[Field]) -> str:
    rec = short(item.name)
    lines = [f"\nfunc (s {rec}) toC() C.{item.name} {{\n\tvar raw C.{item.name}\n"]
    if item.sized:
        lines.append(
            "\t// SAFETY: unsafe.Sizeof is evaluated at compile time and dereferences nothing.\n"
            "\traw.struct_size = C.uint32_t(unsafe.Sizeof(raw))\n"
        )
    for fld in fields:
        target = f"raw.{_c_field(fld.name)}"
        source = f"s.{_camel(fld.name)}"
        if _nested_numbers(api, fld):
            lines.append(f"\t{target} = {source}.toC()\n")
        else:
            lines.append(f"\t{target} = {CTYPES_GO[fld.type]}({source})\n")
    lines.append("\treturn raw\n}\n")
    return "".join(lines)


def _record_struct(api: Api, item: Struct) -> str:
    fields = [f for f in item.fields if f.name != "struct_size"]
    kept = [(f, v) for f in fields if (v := _go_record_field(api, f)) is not None]
    rec = short(item.name)
    rows = [(_camel(f.name), v[0]) for f, v in kept]
    out = [f"\n// {rec}: {item.doc}\ntype {rec} struct {{\n{_align_rows(rows, '\t')}}}\n"]
    out.append(_from_c_func(item, kept))
    plain = [f for f, _ in kept]
    if _plain(api, plain):
        out.append(_to_c_func(api, item, plain))
    return "".join(out)


def _call_parts(api: Api, fn: Function) -> tuple[list[str], list[str], Struct | None]:
    setup: list[str] = []
    args: list[str] = ["c.rawHandle()"]
    out_struct: Struct | None = None
    for param in fn.params[1:]:
        if param.mode == "error":
            setup.append("var cErr *C.VmafxError")
            args.append("&cErr")
        elif param.mode == "out" and api.is_struct(param.type):
            out_struct = api.struct(param.type)
            setup.append(f"var out C.{param.type}")
            setup.append(
                "// SAFETY: unsafe.Sizeof is evaluated at compile time and dereferences nothing."
            )
            setup.append("out.struct_size = C.uint32_t(unsafe.Sizeof(out))")
            args.append("&out")
        elif param.type == "cstr":
            c_var = f"c{_camel(param.name)}"
            setup.append(f"{c_var} := C.CString({param.name})")
            setup.append(f"defer freeCString({c_var})")
            args.append(c_var)
        else:
            args.append(f"{CTYPES_GO[param.type]}({param.name})")
    return setup, args, out_struct


def _context_method(api: Api, fn: Function) -> str:
    setup, args, out_struct = _call_parts(api, fn)
    params = ", ".join(
        f"{p.name} {GOTYPES[p.type]}"
        for p in fn.params[1:]
        if p.mode not in ("error", "out", "out_handle")
    )
    name = _camel(_method_name(fn))
    ret = f"({short(out_struct.name)}, error)" if out_struct else "error"
    lines = [f"\n// {name}: {fn.doc}\nfunc (c *Context) {name}({params}) {ret} {{\n"]
    lines += [f"\t{line}\n" for line in setup]
    lines.append(f"\tstatus := Status(C.{fn.name}({', '.join(args)}))\n")
    if out_struct is not None:
        rec = short(out_struct.name)
        lines.append(f'\tif err := checkStatus(status, cErr, "{fn.name}"); err != nil {{\n')
        lines.append(f"\t\treturn {rec}{{}}, err\n\t}}\n")
        lines.append(f"\treturn {_lower_first(rec)}FromC(out), nil\n}}\n")
    else:
        lines.append(f'\treturn checkStatus(status, cErr, "{fn.name}")\n}}\n')
    return "".join(lines)


def _context_section(api: Api) -> str:
    if not api.is_handle(CONTEXT):
        return ""
    methods = context_methods(api)
    _refuse_collisions("Context", methods, lambda fn: _camel(_method_name(fn)))
    out = [
        "\n// Context wraps a VmafxContext handle; close it with Close.\n"
        "type Context struct {\n"
        "\thandle *C.VmafxContext\n"
        "}\n\n"
        "// New creates a VmafxContext; pass nil for default configuration.\n"
        "func New(config *ContextConfig) (*Context, error) {\n"
        "\tvar raw C.VmafxContextConfig\n"
        "\tvar cfgPtr *C.VmafxContextConfig\n"
        "\tif config != nil {\n"
        "\t\traw = config.toC()\n"
        "\t\tcfgPtr = &raw\n"
        "\t}\n"
        "\tvar handle *C.VmafxContext\n"
        "\tvar cErr *C.VmafxError\n"
        "\tstatus := Status(C.vmafx_context_create(cfgPtr, &handle, &cErr))\n"
        '\tif err := checkStatus(status, cErr, "vmafx_context_create"); err != nil {\n'
        "\t\treturn nil, err\n"
        "\t}\n"
        "\treturn &Context{handle: handle}, nil\n"
        "}\n\n"
        "// NewContext creates a VmafxContext; alias for New.\n"
        "func NewContext(config *ContextConfig) (*Context, error) {\n"
        "\treturn New(config)\n"
        "}\n\n"
        "func (c *Context) rawHandle() *C.VmafxContext {\n"
        "\tif c == nil {\n"
        "\t\treturn nil\n"
        "\t}\n"
        "\treturn c.handle\n"
        "}\n\n"
        "// Close destroys the context; on failure it stays open and Close may be retried (ADR-1336).\n"
        "func (c *Context) Close() error {\n"
        "\tif c == nil || c.handle == nil {\n"
        "\t\treturn nil\n"
        "\t}\n"
        "\tvar cErr *C.VmafxError\n"
        "\tstatus := Status(C.vmafx_context_destroy(c.handle, &cErr))\n"
        '\tif err := checkStatus(status, cErr, "vmafx_context_destroy"); err != nil {\n'
        "\t\treturn err\n"
        "\t}\n"
        "\tc.handle = nil\n"
        "\treturn nil\n"
        "}\n\n"
        "// LibvmafHandle returns the libvmaf VmafContext pointer bound to this context.\n"
        "// SAFETY: vmafx_context_libvmaf_handle returns an opaque borrowed C pointer; nil returns nil.\n"
        "func (c *Context) LibvmafHandle() unsafe.Pointer {\n"
        "\t// SAFETY: the conversion only retypes the borrowed pointer; nothing is dereferenced.\n"
        "\treturn unsafe.Pointer(C.vmafx_context_libvmaf_handle(c.rawHandle()))\n"
        "}\n"
    ]
    out += [_context_method(api, fn) for fn in methods]
    return "".join(out)


def _library_function(fn: Function) -> str:
    outs = [p for p in fn.params if p.mode == "out"]
    ins = [p for p in fn.params if p.mode != "out"]
    params = ", ".join(f"{p.name} {GOTYPES[p.type]}" for p in ins)
    name = _camel(_library_method_name(fn))
    setup: list[str] = []
    args: list[str] = []
    for param in fn.params:
        if param.mode == "out":
            setup.append(f"var {param.name} {CTYPES_GO[param.type]}")
            args.append(f"&{param.name}")
        elif param.type == "cstr":
            c_var = f"c{_camel(param.name)}"
            setup.append(f"var {c_var} *C.char")
            setup.append(
                f'if {param.name} != "" {{\n\t\t{c_var} = C.CString({param.name})\n'
                f"\t\tdefer freeCString({c_var})\n\t}}"
            )
            args.append(c_var)
        else:
            args.append(f"{CTYPES_GO[param.type]}({param.name})")
    call = f"C.{fn.name}({', '.join(args)})"
    body = "".join(f"\t{line}\n" for line in setup)
    if fn.returns == "cstr":
        return f"\n// {name}: {fn.doc}\nfunc {name}({params}) string {{\n{body}\treturn C.GoString({call})\n}}\n"
    ret_types = ", ".join(GOTYPES[p.type] for p in outs)
    ret_vals = ", ".join(f"{GOTYPES[p.type]}({p.name})" for p in outs)
    ret_sig = f"({ret_types})" if len(outs) != 1 else ret_types
    return f"\n// {name}: {fn.doc}\nfunc {name}({params}) {ret_sig} {{\n{body}\t{call}\n\treturn {ret_vals}\n}}\n"


def api_text(api: Api) -> str:
    """Render pkg/vmafx/api_gen.go (`//go:build cgo`)."""
    lib_fns = library_functions(api)
    _refuse_collisions("Library", lib_fns, lambda fn: _camel(_library_method_name(fn)))
    parts = [_api_header(api), _abi_and_enums(api)]
    if api.structs:
        parts.append(_layout_assertions(api))
    parts.append(_error_section(api))
    parts += [_record_struct(api, item) for item in api.structs]
    parts.append(_context_section(api))
    parts += [_library_function(fn) for fn in lib_fns]
    return "".join(parts)
