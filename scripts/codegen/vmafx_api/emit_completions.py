"""Shell completions and the man page, generated from the option groups (#2324).

Four completion scripts (bash, zsh, fish, PowerShell) and a man page render
from the same `cli` spellings the `getopt_long()` table uses (emit_cli.py), so
a flag, an alias or a value domain can only be added in the definition and
every consumer moves with one `--write`. The scripts complete every long
spelling (aliases and underscore spellings included), the short options, the
discrete value switches (`cli_values`, e.g. `--json`) and, for options with a
value domain (`values` or `choices`), the argument words of the value itself.

They are registered for both installed command names, `vmaf` and the `vmafx`
symlink (core/tools/meson.build). Installing them with the packages is
#2319's surface; this module only renders the files.
"""

from __future__ import annotations

import textwrap
from collections.abc import Callable

from .emit_cli import cli_options, takes_value
from .model import Api, Option

BANNER_TEXT = (
    "GENERATED by scripts/codegen/vmafx-api.py from core/api/vmafx.toml (ADR-1852),"
    " option groups. Do not edit: change the definition and run"
    " `python3 scripts/codegen/vmafx-api.py --write`."
)
PROGRAMS = ("vmaf", "vmafx")
WIDTH = 80  # wrap columns of the man page option text

NAME_LINE = "score a distorted video against a reference with the VMAFx metrics"


def _domain(option: Option) -> list[str]:
    """The words a value-taking option completes for its argument, in definition order."""
    if option.values:
        return [str(value) for value in option.values]
    return [str(choice) for choice in option.choices]


class _Spelling:
    """One CLI option flattened for the completion emitters."""

    def __init__(self, option: Option) -> None:
        assert option.cli is not None
        self.flags = list(option.cli.flags)
        self.short = option.cli.short
        self.takes_value = takes_value(option)
        self.meta = option.cli.meta or "value"
        self.domain = _domain(option)
        self.value_flags = [flag for _, flag in option.cli.values]
        self.doc = option.doc

    def all_flags(self) -> list[str]:
        """Every switch spelling: the long flags, the value switches and the short."""
        out = list(self.flags) + self.value_flags
        if self.short:
            out.append(f"-{self.short}")
        return out


def spellings(api: Api) -> list[_Spelling]:
    """Every option the command line spells, in definition order."""
    return [_Spelling(option) for option in cli_options(api)]


def _shell_banner(marker: str) -> str:
    return "\n".join(f"{marker} {line}" for line in BANNER_TEXT.split(". ")) + "\n\n"


def _bash_banner() -> str:
    return _shell_banner("#")


def _bash_words(api: Api) -> str:
    words: list[str] = []
    for spelling in spellings(api):
        words += spelling.all_flags()
    return " ".join(words)


def bash_text(api: Api) -> str:
    """core/tools/completions/vmaf.bash."""
    out = [
        _bash_banner(),
        "# Every COMPREPLY goes through this helper: feeding compgen into the",
        "# array with a command substitution would trip shellcheck's SC2207.",
        "_vmaf_compgen()",
        "{",
        "    local word",
        "    COMPREPLY=()",
        '    while IFS="" read -r word; do',
        '        COMPREPLY+=("${word}")',
        '    done < <(compgen "$@")',
        "}",
        "",
        "_vmaf()",
        "{",
        "    local cur prev",
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    prev="${COMP_WORDS[COMP_CWORD-1]}"',
        '    case "${prev}" in',
    ]
    for spelling in spellings(api):
        if spelling.takes_value and spelling.domain:
            words = " ".join(spelling.domain)
            patterns = [*spelling.flags]
            if spelling.short:
                patterns.append(f"-{spelling.short}")
            out += [
                f"        {'|'.join(patterns)})",
                f'            _vmaf_compgen -W "{words}" -- "${{cur}}"',
                "            return 0",
                "            ;;",
            ]
    out += [
        "    esac",
        '    if [[ "${cur}" == -* ]]; then',
        f'        local flags="{_bash_words(api)}"',
        '        _vmaf_compgen -W "${flags}" -- "${cur}"',
        "        return 0",
        "    fi",
        '    _vmaf_compgen -f -- "${cur}"',
        "}",
    ]
    out += [f"complete -o filenames -F _vmaf {program}" for program in PROGRAMS]
    return "\n".join(out) + "\n"


def _zsh_spec(spelling: _Spelling, flag: str) -> str:
    """One `_arguments` spec for one spelling, single-quoted per the zsh spec grammar.
    Every spelling of an option gets its own spec, so aliases and underscore
    spellings complete; the doc text is escaped for the single-quoted string and
    for the `[...]` description block the spec grammar parses."""
    doc = spelling.doc.replace("\\", "\\\\").replace("]", "\\]")
    doc = doc.replace("$", "\\$").replace("`", "\\`").replace("'", "'\\''")
    if spelling.takes_value:
        if spelling.domain:
            argument = f":{spelling.meta}:({' '.join(spelling.domain)})"
        elif "path" in spelling.meta or "file" in spelling.meta:
            argument = f":{spelling.meta}:_files"
        else:
            argument = f":{spelling.meta}:"
        return f"'{flag}[{doc}]{argument}'"
    return f"'{flag}[{doc}]'"


def _zsh_banner() -> str:
    return "#compdef " + " ".join(PROGRAMS) + "\n\n" + _shell_banner("#")


def zsh_text(api: Api) -> str:
    """core/tools/completions/vmaf.zsh."""
    specs: list[str] = []
    for spelling in spellings(api):
        for flag in spelling.all_flags():
            specs.append(_zsh_spec(spelling, flag))
    body = " \\\n    ".join(specs)
    return _zsh_banner() + "_vmaf() {\n  _arguments -s \\\n    " + body + "\n}\n"


def _fish(text: str) -> str:
    return text.replace("\\", "\\\\").replace("'", "\\'")


def fish_text(api: Api) -> str:
    """core/tools/completions/vmaf.fish."""
    out = [_fish_banner()]
    for spelling in spellings(api):
        parts = ["complete"]
        parts += [f"-c {program}" for program in PROGRAMS]
        parts += [f"-l {flag[2:]}" for flag in spelling.flags]
        parts += [f"-l {flag[2:]}" for flag in spelling.value_flags]
        if spelling.short:
            parts.append(f"-s {spelling.short}")
        if spelling.takes_value:
            parts.append("-r")
            if spelling.domain:
                parts.append("-x")
                parts.append("-a '" + _fish(" ".join(spelling.domain)) + "'")
        parts.append("-d '" + _fish(spelling.doc) + "'")
        out.append(" ".join(parts))
    return "\n".join(out) + "\n"


def _fish_banner() -> str:
    return _shell_banner("#")


def _ps(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def powershell_text(api: Api) -> str:
    """core/tools/completions/vmaf.ps1."""
    out = [
        _shell_banner("#"),
        "Register-ArgumentCompleter -Native -CommandName "
        + ",".join(_ps(program) for program in PROGRAMS)
        + " -ScriptBlock {",
        "    param($wordToComplete, $commandAst, $cursorPosition)",
        "    $elements = @($commandAst.CommandElements | ForEach-Object { $_.ToString() })",
        "    $prev = if ($elements.Count -ge 2) { $elements[$elements.Count - 2] } else { '' }",
        "    $domains = @{",
    ]
    for spelling in spellings(api):
        if spelling.takes_value and spelling.domain:
            words = ",".join(_ps(word) for word in spelling.domain)
            keys = [*spelling.flags]
            if spelling.short:
                keys.append(f"-{spelling.short}")
            for key in keys:
                out.append(f"        {_ps(key)} = @({words})")
    out += [
        "    }",
        "    $flags = @( ",
    ]
    flag_words: list[str] = []
    for spelling in spellings(api):
        flag_words += [_ps(flag) for flag in spelling.all_flags()]
    out.append("        " + ", ".join(flag_words))
    out += [
        "    )",
        "    if ($domains.ContainsKey($prev)) {",
        '        $domains[$prev] | Where-Object { $_ -like "$wordToComplete*" }'
        " | ForEach-Object { [System.Management.Automation.CompletionResult]::new($_) }",
        "        return",
        "    }",
        "    if ($wordToComplete -match '^-') {",
        '        $flags | Where-Object { $_ -like "$wordToComplete*" }'
        " | ForEach-Object { [System.Management.Automation.CompletionResult]::new($_) }",
        "    }",
        "}",
    ]
    return "\n".join(out) + "\n"


def _roff(text: str) -> str:
    """Escape one emitted man-page line: roff control characters and dashes."""
    out = text.replace("\\", "\\e").replace("-", "\\-")
    if out.startswith((".", "'")):
        out = "\\&" + out
    return out


def _man_banner() -> str:
    return "\n".join(f'.\\" {line}' for line in BANNER_TEXT.split(". ")) + "\n"


def man_text(api: Api) -> str:
    """core/tools/man/vmaf.1."""
    out = [
        _man_banner(),
        '.TH VMAF 1 "" "vmafx" "User Commands"',
        ".SH NAME",
        _roff("vmaf, vmafx") + " \\- " + _roff(NAME_LINE),
        ".SH SYNOPSIS",
        ".B vmaf",
        ".RI [ options ]",
        ".SH OPTIONS",
    ]
    for spelling in spellings(api):
        names = ", ".join(_roff(flag) for flag in [*spelling.flags, *spelling.value_flags])
        if spelling.short:
            names += ", " + _roff(f"-{spelling.short}")
        if spelling.takes_value:
            names += f" \\fI{spelling.meta}\\fR"
        out.append(".TP")
        out.append(".B " + names)
        lines = textwrap.wrap(
            spelling.doc, width=WIDTH, break_on_hyphens=False, break_long_words=False
        )
        if not lines:
            lines = [""]
        lines = [_roff(line) for line in lines]
        if spelling.takes_value and spelling.domain:
            # Appended after the wrap so the backslash of the roff optional-break
            # escape survives: the renderer breaks the filled line at `\:`, which
            # keeps a long value list from oversetting the page (groff -man -ww).
            lines[-1] += " One of: " + "|\\:".join(_roff(word) for word in spelling.domain) + "."
        out += lines
    return "\n".join(out) + "\n"


OUTPUT_TEXTS: dict[str, Callable[[Api], str]] = {
    "core/tools/completions/vmaf.bash": bash_text,
    "core/tools/completions/vmaf.zsh": zsh_text,
    "core/tools/completions/vmaf.fish": fish_text,
    "core/tools/completions/vmaf.ps1": powershell_text,
    "core/tools/man/vmaf.1": man_text,
}
