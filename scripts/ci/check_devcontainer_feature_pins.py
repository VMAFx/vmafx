"""Every Dev Container feature resolves through the generated feature lock.

`.devcontainer/devcontainer.json` is generated by praetor and keeps the major
tags its archetype declares. The exact release and digest live in
`.devcontainer/devcontainer-lock.json`, which the Dev Containers CLI writes. A
major-only reference is fine only when a lock record names an exact version and
a ``@sha256`` digest for it; a missing or mutable record fails the gate.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CONFIG = REPO / ".devcontainer/devcontainer.json"
LOCK = REPO / ".devcontainer/devcontainer-lock.json"
EXACT_RELEASE = re.compile(r"^\d+\.\d+\.\d+$")
DIGEST = re.compile(r"^sha256:[0-9a-f]{64}$")
DIGEST_REFERENCE = re.compile(r"^[^@]+@sha256:[0-9a-f]{64}$")


def _features(
    document: object, label: str, *, allow_empty: bool = False
) -> tuple[dict[str, object] | None, list[str]]:
    if not isinstance(document, dict):
        return None, [f"{label} is not an object"]
    features = document.get("features")
    if not isinstance(features, dict):
        return None, [f"{label} features is missing or not an object"]
    if not features and not allow_empty:
        return None, [f"{label} features is empty"]
    return features, []


def _base(reference: str) -> str:
    without_digest = reference.split("@", 1)[0]
    return without_digest.rsplit(":", 1)[0].lower()


def findings(config: object, lock: object) -> list[str]:
    wanted, problems = _features(config, "devcontainer.json")
    records, lock_problems = _features(lock, "devcontainer-lock.json", allow_empty=True)
    problems.extend(lock_problems)
    if wanted is None or records is None:
        return problems
    by_key = {key.lower(): value for key, value in records.items()}
    for reference in wanted:
        if not isinstance(reference, str):
            problems.append(f"feature reference is not a string: {reference!r}")
            continue
        record = by_key.get(reference.lower())
        if not isinstance(record, dict):
            problems.append(f"{reference} has no devcontainer-lock.json record")
            continue
        version = record.get("version")
        if not isinstance(version, str) or not EXACT_RELEASE.fullmatch(version):
            problems.append(f"{reference} lock version is not an exact release (want x.y.z)")
        resolved = record.get("resolved")
        if not isinstance(resolved, str) or not DIGEST_REFERENCE.fullmatch(resolved):
            problems.append(f"{reference} lock resolved value is not an @sha256 digest")
        elif _base(resolved) != _base(reference):
            problems.append(f"{reference} lock resolved value names {resolved}")
        integrity = record.get("integrity")
        if not isinstance(integrity, str) or not DIGEST.fullmatch(integrity):
            problems.append(f"{reference} lock integrity value is not a sha256 digest")
    return problems


def main(argv: list[str]) -> int:
    config_path = Path(argv[1]) if len(argv) > 1 else CONFIG
    lock_path = config_path.with_name("devcontainer-lock.json")
    try:
        config = json.loads(config_path.read_text(encoding="utf-8"))
        lock = json.loads(lock_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        print(f"check-devcontainer-feature-pins: {error}", file=sys.stderr)
        return 2
    problems = findings(config, lock)
    for problem in problems:
        print(f"::error title=devcontainer feature pin::{problem}", file=sys.stderr)
    if problems:
        return 1
    features = config["features"]
    print(f"check-devcontainer-feature-pins: OK ({len(features)} locked feature pins)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
