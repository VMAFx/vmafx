// bypass_unit_test.go — unit tests for Loader lifecycle methods and the
// bpf2go-stub Close helpers.
//
// None of these tests require kernel privileges: they exercise the Go-side
// nil-guard, context-cancellation, and resource-cleanup paths without ever
// loading a real eBPF program.
//
// Coverage targets:
//   - Loader.Stop (nil ringReader + nil objs guard)
//   - Loader.drainLoop context-cancel exit
//   - Loader.closeLinks with empty and populated (mock) link slices
//   - rcloneBypassObjects.Close / rcloneBypassPrograms.Close /
//     rcloneBypassMaps.Close (stub generated-code paths)
//
// ADR-0779: rclone FUSE bypass eBPF program.
package bpf

import (
	"context"
	"log/slog"
	"testing"
	"time"

	"github.com/cilium/ebpf/link"
)

// TestStop_NilLoader verifies that Stop() on a freshly-created Loader
// (ringReader == nil, no links, zero-value objs) returns without panicking.
// The nil-check guard on l.ringReader must be present for this to pass.
func TestStop_NilLoader(t *testing.T) {
	t.Parallel()
	l := New("", slog.Default())
	// ringReader, links, and objs are all zero-valued; Stop must not panic.
	l.Stop()
}

// TestStop_IdempotentAfterDoubleCall verifies that calling Stop twice in
// succession does not panic (important for deferred cleanup paths).
func TestStop_IdempotentAfterDoubleCall(t *testing.T) {
	t.Parallel()
	l := New("/custom-prefix", slog.Default())
	l.Stop()
	l.Stop()
}

// TestCloseLinks_EmptySlice verifies that closeLinks on a Loader with an
