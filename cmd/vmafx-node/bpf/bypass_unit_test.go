// TestIsBypassFD_PopulatedCache verifies IsBypassFD returns the stored path
// when the fd_key is present in activeFDs.
func TestIsBypassFD_PopulatedCache(t *testing.T) {
	t.Parallel()

	l := New("", nil)

	const pid = uint32(9999)
	const fd = uint32(7)
	fdKey := (uint64(pid) << 32) | uint64(fd)
	const wantPath = "/rclone-mount/video.yuv"

	l.mu.Lock()
	l.activeFDs[fdKey] = wantPath
	l.mu.Unlock()

	gotPath, ok := l.IsBypassFD(pid, fd)
	if !ok {
		t.Fatalf("IsBypassFD: got ok=false, want true")
	}
	if gotPath != wantPath {
		t.Errorf("IsBypassFD: got path %q, want %q", gotPath, wantPath)
	}
}

// TestIsBypassFD_WrongPidMiss verifies IsBypassFD returns false when the pid
// component of the fdKey does not match.
func TestIsBypassFD_WrongPidMiss(t *testing.T) {
	t.Parallel()

	l := New("", nil)
	const storedPid = uint32(1111)
	const storedFd = uint32(3)
	fdKey := (uint64(storedPid) << 32) | uint64(storedFd)

	l.mu.Lock()
	l.activeFDs[fdKey] = "/some/path"
	l.mu.Unlock()

	// Query with a different pid — should miss.
	_, ok := l.IsBypassFD(2222, storedFd)
	if ok {
		t.Error("IsBypassFD: expected cache miss for wrong pid, got hit")
	}
}
