static char *test_vif_get_filter(void)
{
    float buffer[128];
    for (int i = 0; i < NUM_KERNELSCALES; i++) {
        float kernelscale = valid_kernelscales[i];
        for (int scale = 0; scale < 5; scale++) {
            int size = vif_get_filter_size(scale, kernelscale);
            mu_assert("vif_get_filter_size returns incorrect size",
                      size == test_vif_filter1d_width[i][scale]);
            vif_get_filter(buffer, scale, kernelscale);
            mu_assert("vif_get_filter returns incorrect values",
                      all_elements_close(buffer, test_vif_filter1d_table_s[i][scale], size));
        }
    }
    return NULL;
}

static char *test_speed_get_antialias_filter(void)
{
    float buffer[128];
    for (int i = 0; i < NUM_KERNELSCALES; i++) {
        float kernelscale = valid_kernelscales[i];
        int size = vif_get_filter_size(1, kernelscale);
        mu_assert("vif_get_filter_size returns incorrect size",
                  size == test_vif_filter1d_width[i][1]);
        speed_get_antialias_filter(buffer, 4, kernelscale);
        mu_assert("speed_get_antialias_filter returns incorrect values",
                  all_elements_close(buffer, test_speed_filter1d_table_s[i], size));
    }
    return NULL;
}

static char *test_validate_kernelscale(void)
{
    for (int i = 0; i < NUM_KERNELSCALES; i++) {
        float kernelscale = valid_kernelscales[i];
        mu_assert("validate_kernelscales rejects valid kernelscale",
                  vif_validate_kernelscale(kernelscale));
    }
    // Update this if any of these ever ends up becoming a valid kernelscale
    const float invalid_kernelscales[4] = {0.0f, 4.0f, -1.0f, 1.2f};
    for (int i = 0; i < 4; i++) {
        float kernelscale = invalid_kernelscales[i];
        mu_assert("validate_kernelscales accepts invalid kernelscale",
                  !vif_validate_kernelscale(kernelscale));
    }
    return NULL;
}

char *run_tests(void)
{
    mu_run_test(test_vif_get_filter);
    mu_run_test(test_speed_get_antialias_filter);
    mu_run_test(test_validate_kernelscale);

    return NULL;
}

