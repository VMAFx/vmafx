/*
 * CAMBI CPU vs. CUDA parity (ADR-0360, device-resident since ADR-1379).
 *
 * CAMBI (Contrast-Aware Multiscale Banding Index) is a JND-tuned banding
 * detector with non-trivial multi-scale filtering. It is implemented by
 * cambi.c (CPU scalar / AVX2 / AVX-512 / NEON) and by integer_cambi_cuda.c +
 * integer_cambi/cambi_score.cu. Both backends require >= 216 in at least one
 * dimension (CAMBI_MIN_WIDTH_HEIGHT).
 *
 * Tolerance: none. Since ADR-1379 the CUDA twin runs every stage on the
 * device with integer or float-for-float arithmetic and an exact top-K sum,
 * so each of the PARITY_FRAMES frames must match the CPU score bit for bit
 * (the ADR-0214 gate in scripts/ci/cross_backend_parity_gate.py is the looser,
 * cross-resolution contract). The same assertions as test_sycl_cambi_parity.c
 * (ADR-1357).
 *
 * Skip behaviour: when vmaf_cuda_state_init() fails (no CUDA driver or no
 * device visible) the device halves emit "[skip: no CUDA device]" and the
 * binary exits 77, meson's "skipped" status.
 */

