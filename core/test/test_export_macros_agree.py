"""VMAFX_EXPORT expands as VMAF_EXPORT does on every compiler family.

libvmaf/macros.h (hand-written) and vmafx/types.h (generated by
scripts/codegen/vmafx_api/emit_c.py) each define an export macro. VMAF_EXPORT
learned that GCC on MinGW has no ELF visibility (#2400); VMAFX_EXPORT kept
`visibility("default")` there, and the Windows UCRT64 LTO link failed with
"visibility attribute not supported in this configuration" (-Werror=attributes)
at src/vmafx/bridge.c and model.c. The contract: preprocessed for native GCC or
clang, MinGW GCC, MinGW clang and MSVC, both macros have the same expansion.

Usage: test_export_macros_agree.py --cc=<word>... --cc-syntax=<gcc|msvc> <public include dir>
Skips (77, reason printed) under the msvc syntax: cl.exe cannot print the macro table
(-dM); the GCC and clang legs run it.
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from meson_cc import take_cc, take_value

TIMEOUT = 60  # seconds per preprocessor run (HISS-02)
CC = take_cc(sys.argv)
MSVC_SYNTAX = take_value(sys.argv, "cc-syntax") == "msvc"
INCLUDE = Path(sys.argv.pop(1)) if len(sys.argv) > 1 else Path()
MACROS = ("VMAF_EXPORT", "VMAFX_EXPORT")
DEFINE = re.compile(r"^#define (VMAFX?_EXPORT)(?: (.*))?$", re.MULTILINE)
SOURCE = "#include <libvmaf/macros.h>\n#include <vmafx/types.h>\n"
# The compiler families, as the predefined macros the headers test. -U__clang__
# makes a clang host preprocess as GCC; a GCC host has nothing to undefine.
FAMILIES = {
    "native": [],
    "MinGW GCC": ["-D__MINGW32__", "-U__clang__"],
    "MinGW clang": ["-D__MINGW32__", "-D__clang__"],
    "MSVC": ["-D_MSC_VER=1940"],
}
# The generated definition before it learned MinGW: a planted defect.
PLANTED_TYPES_H = """#ifndef VMAFX_EXPORT
#if defined(_MSC_VER)
#define VMAFX_EXPORT __declspec(dllexport)
#elif defined(__GNUC__) || defined(__clang__)
#define VMAFX_EXPORT __attribute__((visibility("default")))
#else
#define VMAFX_EXPORT
#endif
#endif
"""


def expansions(include_dirs: list[Path], defines: list[str]) -> dict[str, str]:
    """The body of each export macro after the headers, for one compiler family."""
    argv = [*CC, "-E", "-dM", "-x", "c", "-", *(f"-I{d}" for d in include_dirs), *defines]
    # The build's compiler on a fixed source; no shell.
    done = subprocess.run(  # noqa: S603
        argv, input=SOURCE, capture_output=True, text=True, check=False, timeout=TIMEOUT
    )
    if done.returncode != 0:
        raise RuntimeError(f"{' '.join(argv)} failed: {done.stderr}")
    return {name: (body or "").strip() for name, body in DEFINE.findall(done.stdout)}


def native_is_mingw_gcc() -> bool:
    """Whether the build's own compiler is GCC targeting MinGW, as on the UCRT64 leg.

    The "native" family then preprocesses as "MinGW GCC" does, so a definition
    without the MinGW branch is wrong in both families.
    """
    argv = [*CC, "-E", "-dM", "-x", "c", "-"]
    # The build's compiler on an empty source; no shell.
    done = subprocess.run(  # noqa: S603
        argv, input="", capture_output=True, text=True, check=False, timeout=TIMEOUT
    )
    if done.returncode != 0:
        raise RuntimeError(f"{' '.join(argv)} failed: {done.stderr}")
    defined = set(re.findall(r"^#define (\w+)", done.stdout, re.MULTILINE))
    return "__MINGW32__" in defined and "__clang__" not in defined


def disagreements(include_dirs: list[Path]) -> list[str]:
    out = []
    for family, defines in FAMILIES.items():
        found = expansions(include_dirs, defines)
        if set(found) != set(MACROS):
            out.append(f"{family}: defined {sorted(found)}")
        elif found["VMAF_EXPORT"] != found["VMAFX_EXPORT"]:
            out.append(
                f"{family}: VMAF_EXPORT={found['VMAF_EXPORT']!r} VMAFX_EXPORT={found['VMAFX_EXPORT']!r}"
            )
    return out


class ExportMacrosAgree(unittest.TestCase):
    def test_both_macros_expand_alike_on_every_family(self) -> None:
        self.assertEqual(disagreements([INCLUDE]), [])

    def test_mingw_gcc_gets_no_visibility_attribute(self) -> None:
        found = expansions([INCLUDE], FAMILIES["MinGW GCC"])
        self.assertEqual(found["VMAFX_EXPORT"], "")

    def test_planted_definition_without_mingw_is_refused(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            planted = Path(raw)
            (planted / "vmafx").mkdir()
            (planted / "vmafx" / "types.h").write_text(PLANTED_TYPES_H, encoding="utf-8")
            (planted / "libvmaf").mkdir()
            macros = (INCLUDE / "libvmaf" / "macros.h").read_text(encoding="utf-8")
            (planted / "libvmaf" / "macros.h").write_text(macros, encoding="utf-8")
            found = disagreements([planted])
        expected = {"MinGW GCC", "native"} if native_is_mingw_gcc() else {"MinGW GCC"}
        self.assertEqual({entry.split(":", 1)[0] for entry in found}, expected, found)
        self.assertEqual(len(found), len(expected), found)


if __name__ == "__main__":
    if MSVC_SYNTAX:
        print("SKIP: cl.exe cannot print the macro table (-dM); the GCC and clang legs run this")
        sys.exit(77)
    unittest.main()
