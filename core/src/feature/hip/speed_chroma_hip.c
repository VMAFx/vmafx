static int hip_rc(hipError_t rc)
{
    if (rc == hipSuccess)
        return 0;
    switch (rc) {
    case hipErrorOutOfMemory:
        return -ENOMEM;
    case hipErrorInvalidValue:
        return -EINVAL;
    case hipErrorNoDevice:
        return -ENODEV;
    case hipErrorNotSupported:
        return -ENOSYS;
    default:
        return -EIO;
    }
}

static void record_sc_hip_error(int *first_err, hipError_t rc, const char *operation)
{
    if (rc == hipSuccess)
        return;
    vmaf_log(VMAF_LOG_LEVEL_ERROR, "speed_chroma_hip %s failed with HIP error %d\n", operation,
             (int)rc);
    if (!*first_err)
        *first_err = hip_rc(rc);
}

static void release_sc_device_pointer(void **ptr, int *first_err, const char *name)
{
    if (!*ptr)
        return;
    record_sc_hip_error(first_err, hipFree(*ptr), name);
    *ptr = NULL;
}

static void release_sc_host_pointer(float **ptr, int *first_err, const char *name)
{
    if (!*ptr)
        return;
    record_sc_hip_error(first_err, hipHostFree(*ptr), name);
    *ptr = NULL;
}

static int free_hip_buffers(SpeedChromaHipState *s, bool synchronize)
{
    int first_err = 0;
    if (synchronize && s->stream)
        record_sc_hip_error(&first_err, hipStreamSynchronize(s->stream), "stream synchronize");
    release_sc_device_pointer(&s->d_plane, &first_err, "plane free");
    release_sc_device_pointer(&s->d_means, &first_err, "means free");
    release_sc_device_pointer(&s->d_cov_mat, &first_err, "covariance free");
    release_sc_device_pointer(&s->d_indterm_ref, &first_err, "reference indterm free");
    release_sc_device_pointer(&s->d_indterm_dis, &first_err, "distorted indterm free");
    release_sc_device_pointer(&s->d_sol_ref, &first_err, "reference solution free");
    release_sc_device_pointer(&s->d_sol_dis, &first_err, "distorted solution free");
    release_sc_device_pointer(&s->d_R, &first_err, "R matrix free");
    release_sc_device_pointer(&s->d_eigenvalues, &first_err, "eigenvalues free");
    release_sc_device_pointer(&s->d_eigenvalues_ref, &first_err, "reference eigenvalues free");
    release_sc_device_pointer(&s->d_ref_ent, &first_err, "reference entropy free");
    release_sc_device_pointer(&s->d_ref_var, &first_err, "reference variance free");
    release_sc_device_pointer(&s->d_dis_ent, &first_err, "distorted entropy free");
    release_sc_device_pointer(&s->d_dis_var, &first_err, "distorted variance free");
    release_sc_host_pointer(&s->h_cov_mat, &first_err, "host covariance free");
    release_sc_host_pointer(&s->h_ref_ent, &first_err, "host reference entropy free");
    release_sc_host_pointer(&s->h_ref_var, &first_err, "host reference variance free");
    release_sc_host_pointer(&s->h_dis_ent, &first_err, "host distorted entropy free");
    release_sc_host_pointer(&s->h_dis_var, &first_err, "host distorted variance free");
    if (s->module) {
        record_sc_hip_error(&first_err, hipModuleUnload(s->module), "module unload");
        s->module = NULL;
    }
    if (s->stream) {
        record_sc_hip_error(&first_err, hipStreamDestroy(s->stream), "stream destroy");
        s->stream = NULL;
    }
    return first_err;
}

/* Load HSACO module and look up all 5 kernel entry points. */
static int sc_hip_module_load(SpeedChromaHipState *s)
{
    int err = hip_rc(hipModuleLoadData(&s->module, speed_score_hsaco));
    if (!err)
        err = hip_rc(hipModuleGetFunction(&s->func_means, s->module, "speed_means_hip_kernel"));
    if (!err)
        err = hip_rc(hipModuleGetFunction(&s->func_cov, s->module, "speed_cov_hip_kernel"));
    if (!err)
        err = hip_rc(hipModuleGetFunction(&s->func_indterm, s->module, "speed_indterm_hip_kernel"));
    if (!err)
        err = hip_rc(hipModuleGetFunction(&s->func_solve, s->module, "speed_solve_hip_kernel"));
    if (!err)
        err = hip_rc(hipModuleGetFunction(&s->func_score, s->module, "speed_score_hip_kernel"));
    return err;
}

/* Allocate all device + pinned host buffers. */
static int sc_hip_bufs_alloc(SpeedChromaHipState *s)
{
    const size_t stride_px = s->float_stride / sizeof(float);
    const size_t nb = s->dim.num_blocks;
    const size_t plane_bytes = s->dim.alloc_height * stride_px * sizeof(float);
    const size_t indterm_bytes = SC_ELEMENTS * nb * sizeof(float);
    const size_t cov_bytes = SC_ELEMENTS * SC_ELEMENTS * sizeof(float);
    const size_t score_bytes = nb * sizeof(float);

    int err = hip_rc(hipMalloc(&s->d_plane, plane_bytes));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_means, indterm_bytes));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_cov_mat, cov_bytes));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_indterm_ref, indterm_bytes));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_indterm_dis, indterm_bytes));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_sol_ref, indterm_bytes));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_sol_dis, indterm_bytes));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_R, cov_bytes));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_eigenvalues, SC_ELEMENTS * sizeof(float)));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_eigenvalues_ref, SC_ELEMENTS * sizeof(float)));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_ref_ent, score_bytes));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_ref_var, score_bytes));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_dis_ent, score_bytes));
    if (!err)
        err = hip_rc(hipMalloc(&s->d_dis_var, score_bytes));
    if (!err)
        err = hip_rc(hipHostMalloc((void **)&s->h_cov_mat, cov_bytes, 0));
    if (!err)
        err = hip_rc(hipHostMalloc((void **)&s->h_ref_ent, score_bytes, 0));
    if (!err)
        err = hip_rc(hipHostMalloc((void **)&s->h_ref_var, score_bytes, 0));
    if (!err)
        err = hip_rc(hipHostMalloc((void **)&s->h_dis_ent, score_bytes, 0));
    if (!err)
        err = hip_rc(hipHostMalloc((void **)&s->h_dis_var, score_bytes, 0));
    return err;
}

/* Run GPU kernels K1-K3 and download cov_mat + indterm. */
static int run_gpu_pipeline_sc(SpeedChromaHipState *s, const float *h_plane, void *d_indterm,
                               float *h_indterm)
{
    const uint32_t num_blocks = (uint32_t)s->dim.num_blocks;
    const uint32_t num_blocks_h = (uint32_t)s->dim.num_blocks_horizontal;
    const uint32_t op_w = (uint32_t)s->dim.truncated_width;
    const uint32_t stride_px = (uint32_t)(s->float_stride / sizeof(float));
    const uint32_t submatrix_w = (uint32_t)s->dim.submatrix_width;
    const uint32_t submatrix_h = (uint32_t)s->dim.submatrix_height;
    const size_t plane_bytes = s->dim.truncated_height * stride_px * sizeof(float);
    const size_t indterm_bytes = (size_t)SC_ELEMENTS * num_blocks * sizeof(float);

    hipError_t rc =
        hipMemcpyAsync(s->d_plane, h_plane, plane_bytes, hipMemcpyHostToDevice, s->stream);
    if (rc != hipSuccess)
        return hip_rc(rc);

    /* K1: means */
    {
        const uint32_t grid_x = (num_blocks + SC_MEANS_BLOCK - 1u) / SC_MEANS_BLOCK;
        void *args[] = {(void *)&s->d_plane,  (void *)&s->d_means,   (void *)&op_w,
                        (void *)&stride_px,   (void *)&num_blocks_h, (void *)&num_blocks,
                        (void *)&submatrix_w, (void *)&submatrix_h};
        rc = hipModuleLaunchKernel(s->func_means, grid_x, 1u, 1u, SC_MEANS_BLOCK, 1u, 1u, 0u,
                                   s->stream, args, NULL);
        if (rc != hipSuccess)
            return hip_rc(rc);
    }
    /* K2: covariance — SP_ELEMENTS×SP_ELEMENTS blocks, 256 threads, shared=256*sizeof(double) */
    {
        const size_t smem = SC_COV_BLOCK * sizeof(double);
        void *args[] = {(void *)&s->d_plane,  (void *)&s->d_means,   (void *)&s->d_cov_mat,
                        (void *)&stride_px,   (void *)&num_blocks_h, (void *)&num_blocks,
                        (void *)&submatrix_w, (void *)&submatrix_h};
        rc = hipModuleLaunchKernel(s->func_cov, SC_ELEMENTS, SC_ELEMENTS, 1u, SC_COV_BLOCK, 1u, 1u,
                                   (uint32_t)smem, s->stream, args, NULL);
        if (rc != hipSuccess)
            return hip_rc(rc);
    }
    /* K3: indterm */
    {
        const uint32_t total = SC_ELEMENTS * num_blocks;
        const uint32_t grid_x = (total + SC_INDTERM_BLOCK - 1u) / SC_INDTERM_BLOCK;
        void *args[] = {(void *)&s->d_plane, (void *)&d_indterm, (void *)&stride_px,
                        (void *)&num_blocks_h, (void *)&num_blocks};
        rc = hipModuleLaunchKernel(s->func_indterm, grid_x, 1u, 1u, SC_INDTERM_BLOCK, 1u, 1u, 0u,
                                   s->stream, args, NULL);
        if (rc != hipSuccess)
            return hip_rc(rc);
    }

    /* D2H: cov_mat and indterm. */
    rc = hipMemcpyAsync(s->h_cov_mat, s->d_cov_mat, SC_ELEMENTS * SC_ELEMENTS * sizeof(float),
                        hipMemcpyDeviceToHost, s->stream);
    if (rc != hipSuccess)
        return hip_rc(rc);
    rc = hipMemcpyAsync(h_indterm, d_indterm, indterm_bytes, hipMemcpyDeviceToHost, s->stream);
    if (rc != hipSuccess)
        return hip_rc(rc);
    rc = hipStreamSynchronize(s->stream);
    return hip_rc(rc);
}

/* uv from u and v, imputing across a singular channel exactly as extract_fex()
 * in speed.c does. */
static float combine_chroma_uv(float score_u, float score_v, bool singular_u, bool singular_v)
{
    if (singular_u && !singular_v)
        return score_v;
    if (singular_v && !singular_u)
        return score_u;
    return (score_u + score_v) * 0.5f;
}

/* CPU linear algebra + upload R/solution + K4 solve. */
static int run_cpu_linalg_sc(SpeedChromaHipState *s, float *h_indterm, void *d_sol,
                             bool *singular_out)
{
    const int sz = (int)SC_ELEMENTS;
    const int nb = (int)s->dim.num_blocks;
    const size_t indterm_bytes = (size_t)SC_ELEMENTS * (size_t)nb * sizeof(float);

    speed_internal_compute_eigenvalues(s->h_cov_mat, s->h_eigenvalues, sz, s->h_eig_scratch);
    bool regular = speed_internal_is_matrix_regular(s->h_eigenvalues, (size_t)sz);

    hipError_t rc = hipSuccess;
    /* A singular matrix is a score condition, not a hard failure (ADR-1202). */
    *singular_out = !regular;
    speed_internal_tally_solve(&s->singular_tally, !regular, "speed_chroma_hip");
    if (!regular) {
        /* The score kernel reads the device solution; zero it for singular input. */
        rc = hipMemsetAsync(d_sol, 0, indterm_bytes, s->stream);
        if (rc != hipSuccess)
            return hip_rc(rc);
    } else {
        const int qr_err =
            speed_internal_qr_factorize(s->h_cov_mat, sz, s->h_Q, s->h_R, s->h_qr_scratch);
        if (qr_err)
            return qr_err;
        speed_internal_qt_multiply(s->h_Q, h_indterm, sz, nb, s->h_qt_scratch);

        rc = hipMemcpyAsync(s->d_R, s->h_R, (size_t)sz * (size_t)sz * sizeof(float),
                            hipMemcpyHostToDevice, s->stream);
        if (rc != hipSuccess)
            return hip_rc(rc);
        rc = hipMemcpyAsync(d_sol, h_indterm, indterm_bytes, hipMemcpyHostToDevice, s->stream);
        if (rc != hipSuccess)
            return hip_rc(rc);

        /* K4: one device wavefront performs backward substitution per column. */
        const uint32_t u_nb = (uint32_t)nb;
        void *args[] = {(void *)&s->d_R, (void *)&d_sol, (void *)&u_nb};
        rc = hipModuleLaunchKernel(s->func_solve, u_nb, 1u, 1u, s->solve_warp, 1u, 1u, 0u,
                                   s->stream, args, NULL);
        if (rc != hipSuccess)
            return hip_rc(rc);
        rc = hipStreamSynchronize(s->stream);
        if (rc != hipSuccess)
            return hip_rc(rc);
    }

    /* Each pass uploads its eigenvalues; the caller stashes the reference copy. */
    rc = hipMemcpyAsync(s->d_eigenvalues, s->h_eigenvalues, SC_ELEMENTS * sizeof(float),
                        hipMemcpyHostToDevice, s->stream);
    if (rc != hipSuccess)
        return hip_rc(rc);
    rc = hipStreamSynchronize(s->stream);
    return hip_rc(rc);
}

static int launch_score_sc(SpeedChromaHipState *s, uint32_t num_blocks)
{
    const float sigma_nn = (float)s->opt.speed_sigma_nn;
    const uint32_t grid = (num_blocks + SC_SCORE_BLOCK - 1u) / SC_SCORE_BLOCK;
    void *args[] = {
        (void *)&s->d_eigenvalues_ref, (void *)&s->d_eigenvalues, (void *)&s->d_sol_ref,
        (void *)&s->d_sol_dis,         (void *)&s->d_indterm_ref, (void *)&s->d_indterm_dis,
        (void *)&s->d_ref_ent,         (void *)&s->d_ref_var,     (void *)&s->d_dis_ent,
        (void *)&s->d_dis_var,         (void *)&num_blocks,       (void *)&sigma_nn,
    };
    return hip_rc(hipModuleLaunchKernel(s->func_score, grid, 1u, 1u, SC_SCORE_BLOCK, 1u, 1u, 0u,
                                        s->stream, args, NULL));
}

static int download_score_sc(SpeedChromaHipState *s, uint32_t num_blocks)
{
    const size_t ab = (size_t)num_blocks * sizeof(float);
    int err =
        hip_rc(hipMemcpyAsync(s->h_ref_ent, s->d_ref_ent, ab, hipMemcpyDeviceToHost, s->stream));
    if (!err)
        err = hip_rc(
            hipMemcpyAsync(s->h_ref_var, s->d_ref_var, ab, hipMemcpyDeviceToHost, s->stream));
    if (!err)
        err = hip_rc(
            hipMemcpyAsync(s->h_dis_ent, s->d_dis_ent, ab, hipMemcpyDeviceToHost, s->stream));
    if (!err)
        err = hip_rc(
            hipMemcpyAsync(s->h_dis_var, s->d_dis_var, ab, hipMemcpyDeviceToHost, s->stream));
    if (!err)
        err = hip_rc(hipStreamSynchronize(s->stream));
    return err;
}

static void speed_weighted_scores(int mode, float ref_entropy, float dis_entropy, float ref_var,
                                  float dis_var, float *ref_score, float *dis_score)
{
    const float ref_log = log2f(1.0f + ref_var);
    *ref_score = ref_entropy * ref_log;
    switch (mode) {
    case 0:
        *dis_score = dis_entropy * log2f(1.0f + dis_var);
        break;
    case 1:
        *dis_score = dis_entropy * ref_log;
        break;
    case 2:
        *ref_score = ref_entropy * log2f(1.0f + dis_var);
        *dis_score = dis_entropy * log2f(1.0f + dis_var);
        break;
    case 3:
        *ref_score = ref_entropy * log2f(1.0f + (ref_var + dis_var) * 0.5f);
        *dis_score = dis_entropy * log2f(1.0f + (ref_var + dis_var) * 0.5f);
        break;
    case 4:
        *dis_score = dis_entropy * log2f(1.0f + (ref_var + dis_var) * 0.5f);
        break;
    case 5:
        *dis_score = dis_entropy * log2f(1.0f + 0.75f * ref_var + 0.25f * dis_var);
        break;
    case 6:
        *dis_score = dis_entropy * log2f(1.0f + 0.25f * ref_var + 0.75f * dis_var);
        break;
    default:
        *ref_score = 0.0f;
        *dis_score = 0.0f;
        break;
    }
}

static float aggregate_score_sc(const SpeedChromaHipState *s, uint32_t num_blocks)
{
    const float base_entropy =
        (float)SC_ELEMENTS *
        (log2f((1.0f + (float)s->opt.speed_nn_floor) * (float)s->opt.speed_sigma_nn) +
         log2f(2.0f * 3.14159265358979323846f * 2.71828182845904523536f));
    float total = 0.0f;
    for (uint32_t i = 0; i < num_blocks; ++i) {
        const float re = s->h_ref_ent[i];
        const float de = s->h_dis_ent[i];
        if (re < base_entropy && de < base_entropy)
            continue;
        const float rv = s->h_ref_var[i];
        const float dv = s->h_dis_var[i];
        float sr = 0.0f;
        float sd = 0.0f;
        speed_weighted_scores(s->opt.speed_weight_var_mode, re, de, rv, dv, &sr, &sd);
        total += fabsf(sr - sd);
    }
    return total / (float)num_blocks;
}

/* K5 score + D2H + CPU aggregate. */
static int run_score_sc(SpeedChromaHipState *s, float *score_out)
{
    const uint32_t num_blocks = (uint32_t)s->dim.num_blocks;
    int err = launch_score_sc(s, num_blocks);
    if (!err)
        err = download_score_sc(s, num_blocks);
    if (!err)
        *score_out = aggregate_score_sc(s, num_blocks);
    return err;
}

