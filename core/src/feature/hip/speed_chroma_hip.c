static int init_chroma_dimensions(SpeedChromaHipState *s, enum VmafPixelFormat pix_fmt, unsigned w,
                                  unsigned h)
{
    unsigned cw = w;
    unsigned ch = h;
    switch (pix_fmt) {
    case VMAF_PIX_FMT_UNKNOWN:
    case VMAF_PIX_FMT_YUV400P:
        return -EINVAL;
    case VMAF_PIX_FMT_YUV420P:
        cw /= 2u;
        ch /= 2u;
        break;
    case VMAF_PIX_FMT_YUV422P:
        cw /= 2u;
        break;
    case VMAF_PIX_FMT_YUV444P:
        break;
    }

    s->opt = (SpeedInternalOptions){
        .speed_kernelscale = s->speed_chroma_kernelscale,
        .speed_prescale = s->speed_chroma_prescale,
        .speed_prescale_method = s->speed_chroma_prescale_method,
        .speed_sigma_nn = s->speed_chroma_sigma_nn,
        .speed_nn_floor = s->speed_chroma_nn_floor,
        .speed_weight_var_mode = s->speed_weight_var_mode,
    };
    const int err =
        speed_internal_init_dimensions(&s->dim, (int)cw, (int)ch, s->opt.speed_prescale);
    if (err)
        return err;
    s->float_stride = speed_internal_float_stride(s->dim.alloc_width);
    return s->float_stride ? 0 : -EOVERFLOW;
}

static int allocate_chroma_cpu_buffers(SpeedChromaHipState *s)
{
    if (s->dim.alloc_height > SIZE_MAX / s->float_stride ||
        s->dim.num_blocks > SIZE_MAX / (SC_ELEMENTS * sizeof(float)))
        return -EOVERFLOW;
    const size_t plane_bytes = s->dim.alloc_height * s->float_stride;
    const size_t indterm_bytes = SC_ELEMENTS * s->dim.num_blocks * sizeof(float);
    const size_t cov_bytes = SC_ELEMENTS * SC_ELEMENTS * sizeof(float);
    s->h_plane_ref = aligned_malloc(plane_bytes, 32);
    s->h_plane_dis = aligned_malloc(plane_bytes, 32);
    s->h_eigenvalues = aligned_malloc(SC_ELEMENTS * sizeof(float), 32);
    s->h_eig_scratch =
        aligned_malloc((SC_ELEMENTS * SC_ELEMENTS + 4u * SC_ELEMENTS) * sizeof(float), 32);
    s->h_Q = aligned_malloc(cov_bytes, 32);
    s->h_R = aligned_malloc(cov_bytes, 32);
    s->h_qr_scratch = aligned_malloc(4u * cov_bytes, 32);
    s->h_indterm_ref = aligned_malloc(indterm_bytes, 32);
    s->h_indterm_dis = aligned_malloc(indterm_bytes, 32);
    s->h_qt_scratch = aligned_malloc(indterm_bytes, 32);
    if (!s->h_plane_ref || !s->h_plane_dis || !s->h_eigenvalues || !s->h_eig_scratch || !s->h_Q ||
        !s->h_R || !s->h_qr_scratch || !s->h_indterm_ref || !s->h_indterm_dis || !s->h_qt_scratch)
        return -ENOMEM;
    return 0;
}

#ifdef HAVE_HIPCC
static int init_chroma_hip_runtime(SpeedChromaHipState *s)
{
    int err = sc_hip_module_load(s);
    if (!err)
        err = hip_rc(hipStreamCreate(&s->stream));
    int device = 0;
    hipDeviceProp_t properties;
    if (!err)
        err = hip_rc(hipGetDevice(&device));
    if (!err)
        err = hip_rc(hipGetDeviceProperties(&properties, device));
    if (!err && properties.warpSize <= 0)
        err = -EIO;
    if (!err)
        s->solve_warp = (unsigned)properties.warpSize;
    if (!err)
        err = sc_hip_bufs_alloc(s);
    return err;
}
#endif

static int init_chroma_hip(VmafFeatureExtractor *fex, enum VmafPixelFormat pix_fmt, unsigned bpc,
                           unsigned w, unsigned h)
{
    (void)bpc;
    SpeedChromaHipState *const s = fex->priv;
    int err = init_chroma_dimensions(s, pix_fmt, w, h);
#ifndef HAVE_HIPCC
    return err ? err : -ENOSYS;
#else
    if (!err)
        err = allocate_chroma_cpu_buffers(s);
    if (!err)
        err = init_chroma_hip_runtime(s);
    if (!err) {
        s->feature_name_dict =
            vmaf_feature_name_dict_from_provided_features(fex->provided_features, fex->options, s);
        if (!s->feature_name_dict)
            err = -ENOMEM;
    }
    if (err) {
        const int hip_cleanup_err = free_hip_buffers(s, false);
        if (hip_cleanup_err)
            vmaf_log(VMAF_LOG_LEVEL_ERROR, "speed_chroma_hip initialization cleanup failed: %d\n",
                     hip_cleanup_err);
        free_chroma_cpu_buffers(s);
    }
    return err;
#endif
}

#ifdef HAVE_HIPCC
typedef struct ChromaChannelResult {
    float score;
    bool singular;
    int err;
} ChromaChannelResult;

static void prepare_chroma_planes(SpeedChromaHipState *s, const VmafPicture *ref_pic,
                                  const VmafPicture *dist_pic, int channel, float *tmp_filter)
{
    picture_copy(s->h_plane_ref, s->float_stride, ref_pic, -128, ref_pic->bpc, channel);
    speed_internal_filter_and_downscale(&s->dim, &s->opt, s->h_plane_ref, tmp_filter,
                                        s->float_stride);
    picture_copy(s->h_plane_dis, s->float_stride, dist_pic, -128, dist_pic->bpc, channel);
    speed_internal_filter_and_downscale(&s->dim, &s->opt, s->h_plane_dis, tmp_filter,
                                        s->float_stride);
}

static ChromaChannelResult score_chroma_channel(SpeedChromaHipState *s, const VmafPicture *ref_pic,
                                                const VmafPicture *dist_pic, int channel,
                                                float *tmp_filter)
{
    ChromaChannelResult result = {0};
    prepare_chroma_planes(s, ref_pic, dist_pic, channel, tmp_filter);
    result.err = run_gpu_pipeline_sc(s, s->h_plane_ref, s->d_indterm_ref, s->h_indterm_ref);
    bool singular_ref = false;
    if (!result.err)
        result.err = run_cpu_linalg_sc(s, s->h_indterm_ref, s->d_sol_ref, &singular_ref);
    if (!result.err)
        result.err = hip_rc(
            hipMemcpyDtoD(s->d_eigenvalues_ref, s->d_eigenvalues, SC_ELEMENTS * sizeof(float)));
    bool singular_dis = false;
    if (!result.err)
        result.err = run_gpu_pipeline_sc(s, s->h_plane_dis, s->d_indterm_dis, s->h_indterm_dis);
    if (!result.err)
        result.err = run_cpu_linalg_sc(s, s->h_indterm_dis, s->d_sol_dis, &singular_dis);
    if (!result.err && singular_ref == singular_dis)
        result.err = run_score_sc(s, &result.score);
    result.singular = singular_ref || singular_dis;
    return result;
}

static int append_chroma_scores(const SpeedChromaHipState *s, VmafFeatureCollector *collector,
                                unsigned index, const ChromaChannelResult results[2])
{
    static const char *const names[] = {"Speed_chroma_feature_speed_chroma_u_score",
                                        "Speed_chroma_feature_speed_chroma_v_score",
                                        "Speed_chroma_feature_speed_chroma_uv_score"};
    const float uv = combine_chroma_uv(results[0].score, results[1].score, results[0].singular,
                                       results[1].singular);
    const double values[] = {results[0].score, results[1].score, uv};
    int err = 0;
    for (unsigned i = 0; i < 3; i++) {
        const double clipped =
            values[i] < s->speed_chroma_max_val ? values[i] : s->speed_chroma_max_val;
        err |= vmaf_feature_collector_append_with_dict(collector, s->feature_name_dict, names[i],
                                                       clipped, index);
    }
    return err;
}
#endif

static int extract_chroma_hip(VmafFeatureExtractor *fex, VmafPicture *ref_pic,
                              VmafPicture *ref_pic_90, VmafPicture *dist_pic,
                              VmafPicture *dist_pic_90, unsigned index,
                              VmafFeatureCollector *feature_collector)
{
    (void)ref_pic_90;
    (void)dist_pic_90;

#ifndef HAVE_HIPCC
    (void)fex;
    (void)ref_pic;
    (void)dist_pic;
    (void)index;
    (void)feature_collector;
    return -ENOSYS;
#else
    SpeedChromaHipState *const s = fex->priv;
    if (s->dim.alloc_height > SIZE_MAX / s->float_stride / 2u)
        return -EOVERFLOW;
    const size_t tmp_bytes = 2u * s->dim.alloc_height * s->float_stride;
    float *const tmp_filter = aligned_malloc(tmp_bytes, 32);
    if (!tmp_filter)
        return -ENOMEM;
    ChromaChannelResult results[2];
    results[0] = score_chroma_channel(s, ref_pic, dist_pic, 1, tmp_filter);
    results[1] = score_chroma_channel(s, ref_pic, dist_pic, 2, tmp_filter);
    aligned_free(tmp_filter);
    if (results[0].err)
        return results[0].err;
    if (results[1].err)
        return results[1].err;
    return append_chroma_scores(s, feature_collector, index, results);
#endif /* HAVE_HIPCC */
}

static int close_chroma_hip(VmafFeatureExtractor *fex)
{
    SpeedChromaHipState *const s = fex->priv;
    speed_internal_report_singular(&s->singular_tally, "speed_chroma_hip");
    int err = 0;
#ifdef HAVE_HIPCC
    err = free_hip_buffers(s, true);
#endif
    free_chroma_cpu_buffers(s);
    const int dict_err = vmaf_dictionary_free(&s->feature_name_dict);
    if (dict_err) {
        vmaf_log(VMAF_LOG_LEVEL_ERROR, "speed_chroma_hip dictionary free failed: %d\n", dict_err);
        if (!err)
            err = dict_err;
    }
    return err;
}

