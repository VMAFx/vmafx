"""Embed a compiled SPIR-V module as a C source (ADR-3401).

The Vulkan integer path compiles its GLSL compute shaders at build time
(glslangValidator / glslc / glslang) and embeds the resulting SPIR-V into
libvmaf as a word array — the same shape the HIP backend uses for its
xxd-generated HSACO embeds, so no runtime file or section lookup is
needed and the compiled TU carries the embed dependency itself. The
generated source defines a `const uint32_t` array of the SPIR-V words
plus its size in bytes; the one consumer TU declares them extern.

Usage: spv_embed.py <input.spv> <output.c> <array_name>
"""

import struct
import sys

TOP = """\
/* Copyright 2026 luoye-cpu
 * SPDX-License-Identifier: EUPL-1.2
 *
 * GENERATED by core/src/vulkan/spv_embed.py from {src}.
 * Do not edit: the meson custom_target regenerates it from the GLSL
 * compute shader.
 */
#include <stdint.h>

#include <stddef.h>

/* The SPIR-V words of the {name} module. */
const uint32_t {name}[] = {{
"""


def main(argv):
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    src, dst, name = argv[1], argv[2], argv[3]
    with open(src, "rb") as f:
        blob = f.read()
    if len(blob) % 4 != 0 or not blob:
        print(f"spv_embed: {src} is not a non-empty whole number of SPIR-V words", file=sys.stderr)
        return 1
    words = struct.unpack(f"<{len(blob) // 4}I", blob)

    with open(dst, "w", newline="\n") as f:
        f.write(TOP.format(src=src.replace("\\\\", "/").replace("\\", "/"), name=name))
        for i in range(0, len(words), 8):
            chunk = words[i:i + 8]
            f.write("    " + ", ".join(f"0x{w:08x}u" for w in chunk) + ",\n")
        f.write("};\n")
        f.write(f"const size_t {name}_size = sizeof({name});\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
